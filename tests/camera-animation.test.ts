import test from 'node:test';
import assert from 'node:assert/strict';
import { createProject, projectSchema } from '../src/core/model';
import { cameraAnimationDuration, sampleCamera, setCameraPoseAt, type CameraAction } from '../src/core/camera-animation';
import { initialPreviewStage, linePlaybackPlan, linePreviewSnapshot, sampleLinePlayback } from '../src/core/line-preview';
import { applyTextScript, projectToText } from '../src/core/text-script';
import { blueprintFromPerformance, rawSavedBlueprintAction } from '../src/core/blueprint-authoring';
import { arrangePerformanceTimeline, performanceTimeline } from '../src/core/performance-timeline';
import { compileProject } from '../src/runtime/compiler';

const initial = initialPreviewStage().camera;
const camera = (): CameraAction => ({ kind: 'camera', x: .8, y: -.4, zoom: 2, rotation: 40, duration: 2, easing: 'linear', wait: false });
test('camera playhead edits retain original targets and untouched channels', () => {
  const action = camera();
  setCameraPoseAt(action, 1, initial, { x: .2, zoom: 1.8 });
  assert.deepEqual(Object.keys(action.curves!).sort(), ['x', 'zoom']);
  const middle = sampleCamera(initial, action, 1);
  assert.equal(middle.x, .2); assert.equal(middle.zoom, 1.8); assert.equal(middle.y, -.2); assert.equal(middle.rotation, 20);
  const end = sampleCamera(initial, action, 2);
  assert.equal(end.x, .8); assert.equal(end.zoom, 2);
  setCameraPoseAt(action, 3, initial, { x: .6 });
  assert.equal(cameraAnimationDuration(action), 3);
  assert.equal(sampleCamera(initial, action, 2).x, .8);
  assert.equal(sampleCamera(initial, action, 3).x, .6);
});
test('camera independent curves survive text, schema, blueprint and timeline compilation', () => {
  const project = createProject(), action = camera(); action.wait = true;
  setCameraPoseAt(action, 3, initial, { rotation: 12 });
  const node = project.nodes.find(node => node.kind === 'passage')!;
  node.lines[0].text = '镜头曲线验收';
  node.lines[0].actions = [action];
  const saved = projectSchema.parse(JSON.parse(JSON.stringify(project)));
  const restored = applyTextScript(saved, projectToText(saved));
  assert.deepEqual(restored.issues, []);
  const restoredNode = restored.project.nodes.find(item => item.id === node.id)!;
  assert.equal(restoredNode.kind, 'passage'); if (restoredNode.kind !== 'passage') return;
  assert.deepEqual(restoredNode.lines[0].actions, [action]);
  const graph = blueprintFromPerformance(project, [action]); project.blueprints.push(graph);
  const source = graph.nodes.find(node => node.type === 'savedAction')!;
  assert.deepEqual(rawSavedBlueprintAction(source), action);
  const timeline = performanceTimeline(project, graph);
  assert.equal(timeline.reason, undefined); assert.equal(timeline.clips[0].duration, 3); assert.equal(timeline.clips[0].trackId, 'track_camera');
  arrangePerformanceTimeline(project, graph, timeline.clips, timeline.tracks);
  const compiled = compileProject(project);
  assert.deepEqual(compiled.diagnostics.filter(item => item.severity === 'error'), []);
  assert.match(compiled.files['game/story.rpy'], /pause 3/);
  assert.match(compiled.files['game/story.rpy'], /linear 1 rotate 12/);
});
test('camera curves continue across dialogue and are replaced from the current sampled pose', () => {
  const project = createProject(), action = camera();
  setCameraPoseAt(action, 3, initial, { rotation: 12 });
  const node = project.nodes.find(node => node.kind === 'passage')!;
  node.lines = [{ id: 'prior', text: '', actions: [action, { kind: 'pause', seconds: 1 }] }, { id: 'current', text: '', actions: [] }];
  const snapshot = linePreviewSnapshot(project, { nodeId: node.id, lineId: 'current' });
  assert.equal(snapshot.before.cameraMotion!.elapsed, 1);
  const plan = linePlaybackPlan(snapshot.before, snapshot.actions);
  assert.equal(plan.until, 2000);
  assert.equal(sampleLinePlayback(snapshot.before, plan, 2000).state.camera.rotation, 12);
  const replacement = { ...camera(), x: 0, duration: 1 };
  const replaced = linePlaybackPlan(snapshot.before, [replacement]);
  assert.equal(sampleLinePlayback(snapshot.before, replaced, 500).state.camera.x, .2);
});
