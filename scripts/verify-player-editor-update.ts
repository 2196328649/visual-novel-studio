import assert from 'node:assert/strict';
import { promises as fs } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { expect } from '@playwright/test';
import { assetFiles, type Project } from '../src/core/model';
import { assetSourcePath } from '../src/desktop/project-store';
import { templateVoiceArtworkAssetIds } from '../src/core/template-repairs';
import { historyTemplateAssets } from '../src/core/template-history';
import { exportSettings } from '../src/core/export-settings';
import { launchDesktopFixture } from './lib/desktop-fixture';
import { writeUiHistoryAudio } from './lib/ui-history-preview-fixture';

const root = path.resolve('.'), source = path.resolve(process.argv[2]);
const output = path.join(root, 'artifacts/player-editor-update', new Date().toISOString().replaceAll(':', '-'));
const preserved = await Promise.all(['', '.autosave', '.previous'].map(async suffix => ({ file: source + suffix, bytes: await fs.readFile(source + suffix) })));
const project: Project = JSON.parse(preserved[0].bytes.toString('utf8'));
for (const asset of project.assets) {
  const files = Object.fromEntries(assetFiles(asset).map(relative => [relative, assetSourcePath(path.dirname(source), asset, relative)]));
  asset.externalFiles = files; asset.externalPath = files[asset.path];
}
await writeUiHistoryAudio(output);
project.assets.push({ id: 'qa_voice', name: '验收语音', kind: 'audio', category: 'voice', path: 'assets/voice_0.wav' });
project.nodes.push({ id: 'qa_history', name: '仅副本中的历史验收数据', kind: 'passage', x: 0, y: 0, sceneId: project.scenes[0].id, lines: Array.from({ length: 20 }, (_, index) => ({ id: 'qa_line_' + index, text: index % 3 === 0 ? '旁白也应对齐对白列。' : index % 3 === 1 ? '这条对白验证角色、按钮和正文各占固定列。' : '这是一条需要自动换行的长对白，换行后正文应继续在同一列。'.repeat(5), ...(index % 3 ? { speakerId: project.characters[index % project.characters.length].id, voiceId: 'qa_voice' } : {}), actions: [] })) });
project.exportSettings = { ...project.exportSettings!, platform: 'windows', fileName: '', directory: '' };
delete project.scriptText;
const projectFile = path.join(output, 'project.vns.json'), destination = path.join(output, '游戏导出');
await fs.mkdir(destination, { recursive: true });
await fs.writeFile(projectFile, JSON.stringify(project));
const app = await launchDesktopFixture({ root, projectFile, profile: path.join(output, 'profile') });
const editor = await app.firstWindow(), errors: string[] = [];
editor.on('pageerror', e => errors.push(e.message));
try {
  await expect(editor.locator('.project-title strong')).toHaveText(project.name, { timeout: 45000 });
  const loaded = await editor.evaluate(async () => (await window.studio!.getInitial()).project);
  assert.deepEqual(loaded.nodes, project.nodes);
  for (const id of [...templateVoiceArtworkAssetIds, ...historyTemplateAssets]) assert.ok(loaded.assets.some(a => a.id === id), 'Missing restored artwork ' + id);
  const history = loaded.ui.components.find(c => c.id === 'ai_history_items')!;
  assert.equal(history.style?.fontAssetId, historyTemplateAssets[0]);
  assert.equal(history.list?.historyNameFontSize, 32);
  assert.equal(history.list?.historyScrollbar?.thumb?.idle, historyTemplateAssets[2]);
  for (const id of ['ai_gallery_voicecollection', 'ai_musicroom_voicecollection', 'ai_voicecollection_voicecollection']) assert.ok(loaded.ui.components.find(c => c.id === id)?.skin?.idle);
  const voices = loaded.ui.components.find(c => c.id === 'ai_voicecollection_items')!;
  assert.ok(voices.skin?.idle && voices.list?.voiceFavoriteSkin?.idle);
  await fs.writeFile(path.join(output, 'loaded-project.json'), JSON.stringify(loaded, null, 2));
  await editor.locator('[data-workspace-tab="ui"]').click();
  await editor.getByLabel('设计页面', { exact: true }).selectOption('voiceCollection');
  await expect(editor.locator('[data-component-id="ai_voicecollection_items"]')).toBeVisible();
  await editor.screenshot({ path: path.join(output, 'voice-artwork-restored.png') });
  await editor.getByLabel('设计页面', { exact: true }).selectOption('history');
  const opened = app.waitForEvent('window');
  await editor.evaluate(async project => window.studio!.openUiPreviewWindow!({ project, components: project.ui.components, pageId: 'ui:history' }), loaded);
  const preview = await opened;
  preview.on('pageerror', e => errors.push(e.message));
  const frame = preview.getByLabel('参数联动预演画面', { exact: true }), viewport = frame.locator('[data-history-viewport]');
  await expect(viewport.locator('[data-line-id]')).toHaveCount(20);
  const bar = frame.getByRole('scrollbar', { name: '历史对话滚动条', exact: true });
  await expect(bar).toBeVisible();
  await expect(bar).toHaveAttribute('aria-disabled', 'false');
  await bar.focus(); await bar.press('Home');
  await expect.poll(() => viewport.evaluate(e => e.scrollTop)).toBe(0);
  const geometry = await viewport.evaluate(element => Array.from(element.querySelectorAll('[data-line-id]')).slice(0, 3).map(row => {
    const name = row.querySelector('[data-history-speaker]')!, text = row.querySelector('[data-history-text]')!, controls = Array.from(row.querySelectorAll('[data-history-control]'));
    return { text: text.textContent, nameRight: name.getBoundingClientRect().right, nameWidth: name.getBoundingClientRect().width, nameFont: getComputedStyle(name).fontFamily, nameSize: parseFloat(getComputedStyle(name).fontSize), textX: text.getBoundingClientRect().x, textSize: parseFloat(getComputedStyle(text).fontSize), textHeight: text.getBoundingClientRect().height, controls: controls.map(c => c.getBoundingClientRect().x) };
  }));
  await fs.writeFile(path.join(output, 'geometry.json'), JSON.stringify(geometry, null, 2));
  await frame.screenshot({ path: path.join(output, 'history-preview.png') });
  assert.ok(geometry.every(g => Math.abs(g.textX - geometry[0].textX) < 1 && Math.abs(g.nameRight - geometry[0].nameRight) < 1));
  assert.ok(geometry[2].textHeight > geometry[1].textHeight);
  assert.ok(geometry[1].nameFont.includes(historyTemplateAssets[0]), geometry[1].nameFont);
  assert.ok(Math.abs(geometry[1].nameSize / geometry[1].textSize - 32 / 30) < .01);
  assert.deepEqual(geometry[1].controls, geometry[2].controls);
  await frame.screenshot({ path: path.join(output, 'history-preview.png') });
  const bounds = (await bar.boundingBox())!;
  await preview.mouse.move(bounds.x + bounds.width / 2, bounds.y + 5);
  await preview.mouse.down(); await preview.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height - 5, { steps: 12 }); await preview.mouse.up();
  await expect.poll(() => viewport.evaluate(e => e.scrollTop > 100)).toBe(true);
  await preview.close();
  await app.evaluate(({ dialog, shell }, destination) => {
    (globalThis as any).__openedExport = [];
    dialog.showOpenDialog = (async () => ({ canceled: false, filePaths: [destination] })) as any;
    shell.openPath = async file => { (globalThis as any).__openedExport.push(file); return ''; };
  }, destination);
  await editor.locator('.export-button').click();
  const settings = editor.getByRole('dialog', { name: '作品设置', exact: true });
  await expect(settings.locator('.export-output-preview')).toContainText(exportSettings(project).fileName + '-');
  await expect(settings.getByRole('button', { name: '打开位置', exact: true })).toBeDisabled();
  await settings.getByRole('button', { name: '选择位置', exact: true }).click();
  const location = settings.getByLabel('导出文件位置', { exact: true });
  await expect(location).toHaveValue(path.join(destination, exportSettings(project).fileName));
  await expect.poll(() => location.evaluate(e => { const input = e as HTMLInputElement; return input.value.slice(input.selectionStart!, input.selectionEnd!); })).toBe(exportSettings(project).fileName);
  await expect(settings.getByLabel('文件名称', { exact: true })).toHaveCount(0);
  await expect(settings.getByText('自定义导出名称', { exact: true })).toHaveCount(0);
  const row = settings.locator('.export-location-row');
  assert.equal(await row.locator('input').count(), 1);
  const alignment = await row.evaluate(e => Array.from(e.querySelectorAll('input,button')).map(control => { const rect = control.getBoundingClientRect(); return { center: rect.y + rect.height / 2, text: control.textContent, icons: control.querySelectorAll('svg').length }; }));
  assert.ok(alignment.every(item => Math.abs(item.center - alignment[0].center) < 3), JSON.stringify(alignment));
  assert.ok(alignment.slice(1).every(item => item.text === '' && item.icons === 1));
  await settings.getByRole('button', { name: '打开位置', exact: true }).click();
  await expect.poll(() => app.evaluate(() => (globalThis as any).__openedExport)).toEqual([destination]);
  await location.fill(destination + path.sep);
  await expect(location).toHaveValue(destination + path.sep);
  await settings.getByLabel('游戏版本', { exact: true }).fill('1.0.9');
  await expect(location).toHaveValue(path.join(destination, exportSettings(project).fileName));
  await expect(settings.locator('.export-output-preview')).toContainText(exportSettings(project).fileName + '-1.0.9-win.zip');
  await location.fill(path.join(destination, '新的作品名'));
  await settings.getByRole('button', { name: '选择位置', exact: true }).click();
  await expect(location).toHaveValue(path.join(destination, '新的作品名'));
  await expect(settings.locator('.export-output-preview')).toContainText('新的作品名-1.0.9-win.zip');
  await expect(settings.getByRole('button', { name: '导出', exact: true })).toBeEnabled({ timeout: 30000 });
  await settings.screenshot({ path: path.join(output, 'export-location.png') });
  await settings.getByRole('button', { name: '完成', exact: true }).click();
  await editor.getByRole('button', { name: '保存工程', exact: true }).click();
  await expect.poll(async () => JSON.parse(await fs.readFile(projectFile, 'utf8')).exportSettings?.directory).toBe(destination);
  const saved = JSON.parse(await fs.readFile(projectFile, 'utf8'));
  assert.equal(saved.exportSettings.fileName, '新的作品名');
  await app.evaluate(({ ipcMain }) => {
    ipcMain.removeHandler('studio:export');
    ipcMain.handle('studio:export', (_event, project) => { (globalThis as any).__exported = project; return { ok: true, diagnostics: [], log: '参数验证；完整 EXE 已另行实际打包验收。' }; });
  });
  await editor.locator('.export-button').click();
  await settings.getByRole('button', { name: '导出', exact: true }).click();
  await expect.poll(() => app.evaluate(() => (globalThis as any).__exported?.exportSettings)).toMatchObject({ fileName: '新的作品名', directory: destination });
  assert.deepEqual(errors, []);
  for (const original of preserved) assert.ok(original.bytes.equals(await fs.readFile(original.file)), original.file + ' changed');
  await fs.writeFile(path.join(output, 'report.json'), JSON.stringify({ status: 'passed', source, geometry, errors, checks: ['实际用户工程副本加载时恢复原版历史字体和滑条、语音收藏入口/行/删除按钮图片', '旁白、角色名、语音按钮、长对白固定列对齐；字体字号和滚动条拖动通过', '真实选择/打开位置 IPC，通过隔离对话框与资源管理器副作用验证；配置保存及导出参数通过', '原工程及自动保存、备份均保持原样'], originalHashes: preserved.map(p => ({ file: p.file, sha256: createHash('sha256').update(p.bytes).digest('hex') })) }, null, 2));
  console.log('PASS: ' + output);
} catch (error) {
  await editor.screenshot({ path: path.join(output, 'failure.png') }).catch(() => {});
  await fs.writeFile(path.join(output, 'failure.txt'), String(error)); console.log(output); throw error;
} finally {
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().forEach(w => w.destroy())).catch(() => {}); await app.close();
}
