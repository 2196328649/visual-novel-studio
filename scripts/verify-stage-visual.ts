import assert from 'node:assert/strict';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { expect } from '@playwright/test';
import { createProject, projectSchema } from '../src/core/model';
import { createVisualObject } from '../src/core/visual-object';
import { blueprintFromPerformance, exposePerformanceInputs, performanceInputs, rawSavedBlueprintAction } from '../src/core/blueprint-authoring';
import { launchDesktopFixture } from './lib/desktop-fixture';
import { openStoryMode } from './lib/story-workspace';

const root = path.resolve('.'), output = path.join(root, 'artifacts/stage-visual', new Date().toISOString().replaceAll(':', '-'));
await fs.mkdir(output, { recursive: true });
const project = createProject('跨台词视觉对象编辑验收');
const child = { ...createVisualObject('solid'), name: '内部色块', width: .25, height: .25, startAt: .25 };
child.keyframes.push({ ...child.keyframes[0], x: .9, duration: 3 });
const object = { ...createVisualObject('group'), name: '前文组合', duration: 4, retimeOnDuration: true, children: [child] };
object.width = .8; object.height = .7; object.keyframes[0].rotation = 20; object.keyframes[0].scale = .8;
const graph = blueprintFromPerformance(project, [object], '共享组合'); project.blueprints.push(graph);
exposePerformanceInputs(graph, [performanceInputs(graph).find(field => field.pinId === 'object_duration')!]);
graph.exposedInputs[0].defaultValue = 8;
const passage = project.nodes.find(node => node.kind === 'passage')!;
passage.lines = [{ id: 'prior', text: '对象开始。', actions: [{ kind: 'blueprint', blueprintId: graph.id }, { kind: 'pause', seconds: .5 }] }, { id: 'current', text: '继续编辑内部色块。', actions: [] }];
passage.lines[0].actions.unshift({ kind: 'camera', x: 0, y: 0, zoom: 1.2, rotation: -15, duration: 0, easing: 'linear', wait: false });
const projectFile = path.join(output, 'project.vns.json'); await fs.writeFile(projectFile, JSON.stringify(projectSchema.parse(project)));
const app = await launchDesktopFixture({ root, projectFile, profile: path.join(output, 'profile') });
const page = await app.firstWindow(), errors: string[] = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await expect(page.locator('.project-title strong')).toHaveText(project.name, { timeout: 45000 });
  const open = async () => {
    await openStoryMode(page, 'script');
    await page.locator('#line-current textarea').click();
    await page.getByLabel('演出预览进度', { exact: true }).fill('1');
    await page.getByRole('button', { name: '编辑舞台', exact: true }).click();
    await page.getByLabel('舞台选择视觉对象', { exact: true }).selectOption(JSON.stringify([object.instanceId, child.instanceId]));
  };
  await open();
  const x = page.getByLabel('当前横向位置 %', { exact: true }), rotation = page.getByLabel('当前旋转 度', { exact: true });
  await x.fill('25'); await x.press('Tab');
  await rotation.fill('20'); await rotation.press('Tab');
  await expect(x).toHaveValue('25'); await expect(rotation).toHaveValue('20');
  await expect(page.getByLabel('演出预览进度', { exact: true })).toHaveValue('1');
  await page.getByRole('button', { name: '保存工程', exact: true }).click(); await expect(page.locator('.dirty-dot')).toHaveCount(0);
  const saved = projectSchema.parse(JSON.parse(await fs.readFile(projectFile, 'utf8'))), savedGraph = saved.blueprints.find(item => item.id === graph.id)!;
  const action = rawSavedBlueprintAction(savedGraph.nodes.find(item => item.type === 'savedAction')!);
  assert.equal(action?.kind, 'visual'); if (action?.kind !== 'visual') throw new Error('Missing visual');
  assert.deepEqual(action.children![0].curves!.x!.map(frame => [frame.at, frame.value]), [[0, .5], [.5, .25], [3, .9]]);
  assert.deepEqual(action.children![0].keyframes, child.keyframes);
  assert.equal(savedGraph.exposedInputs[0].defaultValue, 8);
  const savedPassage = saved.nodes.find(item => item.id === passage.id)!;
  assert.equal(savedPassage.kind, 'passage'); if (savedPassage.kind !== 'passage') throw new Error('Missing passage');
  assert.deepEqual(savedPassage.lines[1].actions, []);
  await page.screenshot({ path: path.join(output, 'stage-visual.png') });
  await page.reload(); await expect(page.locator('.project-title strong')).toHaveText(project.name);
  await open(); await expect(x).toHaveValue('25'); await expect(rotation).toHaveValue('20');
  const handle = page.locator(`[data-visual-handle="${child.instanceId}"]`);
  const target = await handle.evaluate(element => {
    const rect = element as SVGRectElement, bounds = rect.getBoundingClientRect(), svg = rect.ownerSVGElement!, matrix = svg.getScreenCTM()!;
    const dx = svg.viewBox.baseVal.width * .1, dy = svg.viewBox.baseVal.height * .05;
    return { x: bounds.x + bounds.width / 2, y: bounds.y + bounds.height / 2, dx: matrix.a * dx + matrix.c * dy, dy: matrix.b * dx + matrix.d * dy };
  });
  await page.mouse.move(target.x, target.y); await page.mouse.down();
  await page.mouse.move(target.x + target.dx, target.y + target.dy, { steps: 6 }); await page.mouse.up();
  await expect.poll(async () => Number(await x.inputValue())).toBeCloseTo(35, 1);
  const y = page.getByLabel('当前纵向位置 %', { exact: true });
  await expect.poll(async () => Number(await y.inputValue())).toBeCloseTo(55, 1);
  await expect(page.getByLabel('舞台选择视觉对象', { exact: true })).toHaveValue(JSON.stringify([object.instanceId, child.instanceId]));
  await handle.press('ArrowRight');
  await expect.poll(async () => Number(await x.inputValue())).toBeCloseTo(36, 1);
  const bounds = await handle.boundingBox(); assert.ok(bounds);
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2); await page.mouse.down();
  await page.mouse.move(bounds.x + bounds.width / 2 + 30, bounds.y + bounds.height / 2, { steps: 3 });
  await page.keyboard.press('Escape'); await page.mouse.up();
  await expect.poll(async () => Number(await x.inputValue())).toBeCloseTo(36, 1);
  await page.getByRole('button', { name: '保存工程', exact: true }).click(); await expect(page.locator('.dirty-dot')).toHaveCount(0);
  const dragged = projectSchema.parse(JSON.parse(await fs.readFile(projectFile, 'utf8')));
  const draggedAction = rawSavedBlueprintAction(dragged.blueprints.find(item => item.id === graph.id)!.nodes.find(item => item.type === 'savedAction')!);
  assert.equal(draggedAction?.kind, 'visual'); if (draggedAction?.kind !== 'visual') throw new Error('Missing dragged object');
  assert.ok(Math.abs(draggedAction.children![0].curves!.x![1].value - .36) < .001);
  assert.equal(draggedAction.children![0].curves!.x![1].at, .5);
  assert.equal(draggedAction.children![0].curves!.x!.at(-1)!.value, .9);
  await expect(page.getByLabel('演出预览进度', { exact: true })).toHaveValue('1');
  await page.screenshot({ path: path.join(output, 'stage-visual-drag.png') });
  await page.locator('.preview-lifetimes > summary').click();
  const rootLife = page.locator(`[data-life-instance="${object.instanceId}"]`), childLife = page.locator(`[data-life-instance="${child.instanceId}"]`);
  await expect(rootLife).toHaveAttribute('data-life-start', '-0.5');
  await expect(rootLife).toHaveAttribute('data-life-end', '7.5');
  await expect(childLife).toHaveAttribute('data-life-start', '0');
  await expect(childLife).toHaveAttribute('data-life-end', '6');
  await expect(childLife).toHaveAttribute('data-life-inherited', 'true');
  await childLife.getByRole('button').press('ArrowRight');
  await expect(page.getByLabel('演出预览进度', { exact: true })).toHaveValue('1.1');
  await childLife.getByRole('button').press('Enter');
  await expect(page.getByLabel('演出预览进度', { exact: true })).toHaveValue('0');
  await page.screenshot({ path: path.join(output, 'inherited-lifetimes.png') });
  assert.deepEqual(errors, []);
  await fs.writeFile(path.join(output, 'report.json'), JSON.stringify({ status: 'passed', checks: ['舞台选择前文组合子对象并修改位置旋转', '当前1秒按前文累计和2倍时长换算写回原始0.5秒', '播放头保持且当前台词不新增动作', '原始终点和公开输入保留，重载姿态一致', '镜头及父组合旋转缩放后拖动子对象，保存局部位移', '方向键移动且Escape取消拖动不写入', '前文组合与子对象生命周期显示累计时间、有效结束点并支持定位'], errors }, null, 2));
} catch (error) { await page.screenshot({ path: path.join(output, 'failure.png') }).catch(() => undefined); throw error; }
finally { await app.close(); console.log(output); }
