import assert from 'node:assert/strict';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { expect, type ElectronApplication, type Page } from '@playwright/test';
import { createServer } from 'vite';
import { launchDesktopFixture } from './lib/desktop-fixture';
import { openStoryMode } from './lib/story-workspace';
import { createProject, projectSchema } from '../src/core/model';
import { applyTextScript } from '../src/core/text-script';
import { isStandaloneNode } from '../src/core/standalone-performance';

const root = path.resolve('.'), output = path.join(root, 'artifacts/module-editing', new Date().toISOString().replaceAll(':', '-'));
await fs.mkdir(output, { recursive: true });
const source = '# 章节：第一章\n# 小章节：庭院\n@章节标题：酒醒城破｜副标题｜7\n@独立演出：第一章进入动画\n# 段落：相遇\n旁白：第一句\n旁白：第二句\n# 段落：离开\n旁白：离开庭院\n# 章节：第二章\n# 小章节：街道\n# 段落：后续\n旁白：第二章正文';
const parsed = applyTextScript(createProject('模块交互验收'), source);
assert.deepEqual(parsed.issues, []);
const projectFile = path.join(output, 'project.vns.json');
await fs.writeFile(projectFile, JSON.stringify(parsed.project));
const chapter = parsed.project.nodes.find(isStandaloneNode)!;
const passage = parsed.project.nodes.find(node => node.name === '相遇')!;
const server = await createServer({ root, server: { host: '127.0.0.1', port: 0, watch: { ignored: ['**/artifacts/**', '**/resources/**'] } } });
await server.listen();
let app: ElectronApplication | undefined, page: Page | undefined;
const errors: string[] = [], checks: string[] = [];
const launch = async () => {
  app = await launchDesktopFixture({ root, profile: path.join(output, 'profile'), projectFile, devUrl: process.env.VNS_VERIFY_BUILT ? undefined : `http://127.0.0.1:${(server.httpServer!.address() as { port: number }).port}` });
  page = await app.firstWindow(); page.on('pageerror', error => errors.push(error.message));
  await app.evaluate(({ BrowserWindow, screen }) => { const win = BrowserWindow.getAllWindows()[0], display = screen.getAllDisplays().find(display => display.id !== screen.getPrimaryDisplay().id) ?? screen.getPrimaryDisplay(); win.setBounds({ x: display.workArea.x, y: display.workArea.y, width: Math.min(1480, display.workArea.width), height: Math.min(940, display.workArea.height) }); });
  await expect(page.locator('.project-title strong')).toHaveText(parsed.project.name, { timeout: 45_000 });
};
const menu = (name: string) => page!.getByRole('menuitem', { name, exact: true });
try {
  await launch(); await openStoryMode(page!, 'script');
  const module = page!.locator('#node-' + chapter.id), dialogue = page!.locator('#node-' + passage.id);
  await expect(module.getByRole('button', { name: '独立演出属性', exact: true })).toHaveCount(0);
  await module.locator('.passage-header').dblclick();
  await page!.getByLabel('模块名称', { exact: true }).fill('开场动画');
  await page!.getByLabel('模块名称', { exact: true }).press('Enter');
  await expect(module.locator('.passage-header')).toHaveText('开场动画');
  await module.getByRole('button', { name: '收起模块', exact: true }).click();
  await expect(module.locator('.module-body')).toBeHidden();
  await module.getByRole('button', { name: '展开模块', exact: true }).click();
  await expect(module.getByLabel('章节标题', { exact: true })).toBeVisible();
  await module.getByLabel('章节标题', { exact: true }).fill('修改后的章名');
  await module.getByLabel('章节标题', { exact: true }).press('Tab');
  await page!.screenshot({ path: path.join(output, '01-module-parameters.png') });
  checks.push('模块仅显示名字，可双击改名、折叠；章节文字可直接编辑');
  await dialogue.locator('.passage-header').click({ button: 'right' });
  await menu('在上方添加剧情模块').click();
  const added = page!.locator('.passage-section').filter({ has: page!.locator('.passage-header', { hasText: '新的剧情' }) });
  await expect(added).toHaveCount(1);
  const addedId = (await added.getAttribute('id'))!.slice(5);
  const order = await page!.locator('.passage-section').evaluateAll(nodes => nodes.map(node => node.id));
  assert.equal(order[order.indexOf('node-' + passage.id) - 1], 'node-' + addedId);
  await added.locator('.passage-header').click({ button: 'right' }); await menu('复制模块').click();
  await dialogue.locator('.passage-header').click({ button: 'right' }); await menu('粘贴到模块下方').click();
  await expect(page!.locator('.passage-header').filter({ hasText: '新的剧情' })).toHaveCount(2);
  await page!.locator('#node-' + addedId).locator('.passage-header').click({ button: 'right' }); await menu('剪切模块').click();
  await expect(page!.locator('#node-' + addedId)).toHaveCount(0);
  await dialogue.locator('.passage-header').click({ button: 'right' }); await menu('粘贴到模块上方').click();
  await expect(page!.locator('.passage-header').filter({ hasText: '新的剧情' })).toHaveCount(2);
  await page!.locator('.passage-header').filter({ hasText: '新的剧情' }).first().click({ button: 'right' }); await menu('删除模块').click();
  await expect(page!.locator('.passage-header').filter({ hasText: '新的剧情' })).toHaveCount(1);
  checks.push('模块上方添加、上下粘贴、复制、剪切、删除正常');
  await dialogue.locator('.story-line').first().click({ button: 'right' }); await menu('在上方插入新台词').click();
  await expect(dialogue.locator('.story-line')).toHaveCount(3);
  await dialogue.locator('.story-line').last().click({ button: 'right' }); await menu('在下方插入新台词').click();
  await expect(dialogue.locator('.story-line')).toHaveCount(4);
  await page!.getByRole('button', { name: '添加模块', exact: true }).click(); await menu('添加独立演出模块').click();
  await expect(page!.locator('.passage-section').last().locator('.passage-header')).toHaveText('新的独立演出');
  checks.push('台词上下插入和列表底部添加正常');
  await openStoryMode(page!, 'text');
  const input = page!.getByLabel('中文文本剧本', { exact: true });
  await expect(input).toHaveValue(/@独立演出：开场动画/);
  await page!.getByRole('button', { name: '折叠相遇', exact: true }).click();
  await expect(input).not.toHaveValue(/第一句/);
  await page!.getByRole('button', { name: '展开相遇', exact: true }).click();
  await expect(input).toHaveValue(/第一句/);
  await page!.getByRole('button', { name: '折叠庭院', exact: true }).click();
  await expect(input).not.toHaveValue(/离开庭院/);
  await page!.getByRole('button', { name: '展开庭院', exact: true }).click();
  await page!.getByRole('button', { name: '折叠第一章', exact: true }).click();
  await page!.screenshot({ path: path.join(output, '02-text-folding.png') });
  await page!.getByRole('button', { name: '展开第一章', exact: true }).click();
  await expect(input).toHaveValue(/修改后的章名/);
  checks.push('文本命名同步；段落、小节、章节均可折叠展开且内容保留');
  const tabs = page!.locator('[data-workspace-tab]');
  const before = await tabs.evaluateAll(nodes => nodes.map(node => (node as HTMLElement).dataset.workspaceTab));
  const first = await tabs.first().boundingBox(), third = await tabs.nth(2).boundingBox();
  assert.ok(first && third);
  await page!.mouse.move(first.x + first.width / 2, first.y + first.height / 2); await page!.mouse.down();
  await page!.waitForTimeout(420);
  await page!.mouse.move(third.x + third.width / 2, third.y + third.height / 2, { steps: 8 }); await page!.mouse.up();
  const after = await tabs.evaluateAll(nodes => nodes.map(node => (node as HTMLElement).dataset.workspaceTab));
  assert.notDeepEqual(after, before); assert.equal(after[2], before[0]);
  await openStoryMode(page!, 'script');
  await page!.locator('.story-directory').getByText('庭院', { exact: true }).click();
  await expect(module.locator('.standalone-node-card > p')).toHaveCount(0);
  await expect(module.locator('.standalone-node-card > button')).toHaveCount(0);
  await module.locator('.action-editor-header').getByRole('button', { name: '编辑演出', exact: true }).click();
  await expect(page!.locator('.timeline-clip')).toHaveCount(1);
  await expect(page!.locator('.timeline-clip')).toContainText('7.00s');
  await expect(page!.getByLabel('演出目标', { exact: true }).locator('option:checked')).toContainText('章节进入演出');
  const library = await page!.getByLabel('演出素材库', { exact: true }).boundingBox();
  const preview = await page!.locator('.timeline-preview').boundingBox();
  const tracks = await page!.getByLabel('时间轴画布', { exact: true }).boundingBox();
  const inspector = await page!.locator('.timeline-inspector').boundingBox();
  assert.ok(library && preview && tracks && inspector);
  assert.ok(library.x + library.width <= preview.x + 1 && preview.x + preview.width <= inspector.x + 1);
  assert.ok(tracks.y >= preview.y + preview.height && inspector.height > preview.height);
  const divider = page!.getByRole('separator', { name: '调整预览与时间轴高度' });
  const box = (await divider.boundingBox())!;
  await page!.mouse.move(box.x + box.width / 2, box.y + box.height / 2); await page!.mouse.down();
  await page!.mouse.move(box.x + box.width / 2, box.y - 75, { steps: 8 }); await page!.mouse.up();
  assert.ok((await page!.getByLabel('时间轴画布', { exact: true }).boundingBox())!.height > tracks.height + 40);
  await page!.locator('.timeline-clip').first().click();
  await expect(page!.getByLabel('演出片段参数', { exact: true })).toBeVisible();
  await page!.screenshot({ path: path.join(output, '04-performance-layout.png') });
  checks.push('摘要已去除，演出框标题右侧进入对应演出；素材、预览、时间轴和右侧属性布局正确，分隔线可拖动');
  await openStoryMode(page!, 'script');
  await expect(module.getByLabel('单独设置标题', { exact: true })).toBeVisible();
  await module.getByLabel('单独设置标题', { exact: true }).check();
  const modeLabel = await module.locator('.blueprint-input-mode label').first().boundingBox();
  assert.ok(modeLabel && modeLabel.height <= 30, '参数勾选标签应保持单行，不能逐字竖排');
  await module.getByLabel('标题', { exact: true }).fill('本模块标题');
  await module.getByLabel('标题', { exact: true }).press('Tab');
  await page!.getByRole('button', { name: '保存工程', exact: true }).click(); await expect(page!.locator('.dirty-dot')).toHaveCount(0);
  const saved = projectSchema.parse(JSON.parse(await fs.readFile(projectFile, 'utf8')));
  const reparsed = applyTextScript(saved, saved.scriptText!.content);
  assert.deepEqual(reparsed.issues, []);
  assert.deepEqual(JSON.parse(JSON.stringify(reparsed.project.nodes)), JSON.parse(JSON.stringify(saved.nodes)));
  await app!.close(); app = undefined; await launch();
  assert.deepEqual(await page!.locator('[data-workspace-tab]').evaluateAll(nodes => nodes.map(node => (node as HTMLElement).dataset.workspaceTab)), after);
  await openStoryMode(page!, 'script');
  await expect(page!.locator('#node-' + chapter.id).locator('.passage-header')).toHaveText('开场动画');
  await expect(page!.locator('#node-' + chapter.id).getByLabel('标题', { exact: true })).toHaveValue('本模块标题');
  checks.push('独立演出转时间轴后参数可单独设置；保存重开保留参数、名称和标签顺序');
  assert.deepEqual(errors, []);
  await page!.screenshot({ path: path.join(output, '03-reopened.png') });
  await fs.writeFile(path.join(output, 'report.json'), JSON.stringify({ status: 'passed', checks, errors }, null, 2));
} catch (error) {
  await page?.screenshot({ path: path.join(output, 'failure.png') }).catch(() => undefined);
  await fs.writeFile(path.join(output, 'failure.json'), JSON.stringify({ error: String(error), checks, errors }, null, 2));
  throw error;
} finally { await app?.close(); await server.close(); console.log(output); }
