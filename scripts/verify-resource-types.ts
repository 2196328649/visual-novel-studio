import assert from 'node:assert/strict';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { expect, type ElectronApplication, type Page } from '@playwright/test';
import { createServer } from 'vite';
import { PNG } from 'pngjs';
import { createProject, projectSchema } from '../src/core/model';
import { createBlueprintGraph } from '../src/core/blueprint';
import { addProjectGraphs, projectGraphs } from '../src/core/project-resources';
import { addTimelineComponent, createTimelinePreset } from '../src/core/timeline-component';
import { insertTimelineAction } from '../src/core/performance-timeline';
import { projectToText } from '../src/core/text-script';
import { currentScriptText } from '../src/core/script-text';
import { enterFixtureProject, installedExecutable, launchDesktopFixture } from './lib/desktop-fixture';

const root = path.resolve('.'), output = path.resolve('artifacts/resource-types', Date.now().toString(36) + '-' + randomUUID().slice(0, 3));
const projectFile = path.join(output, 'project/project.vns.json');
await fs.mkdir(path.dirname(projectFile), { recursive: true });
const project = createProject('资源类型与删除验收');
project.resourceSettings = { importMode: 'copy', syncFolders: false, directory: 'assets' };
const picture = new PNG({ width: 32, height: 18 }); picture.data.fill(200);
await fs.writeFile(path.join(path.dirname(projectFile), 'picture.png'), PNG.sync.write(picture));
project.assets = [{ id: 'qa_picture', name: '验收隐藏图片', kind: 'image', path: 'picture.png' }];
const owner = createBlueprintGraph('function', '验收逻辑'); owner.id = 'qa_owner'; addProjectGraphs(project, owner);
const { timeline } = addTimelineComponent(project, owner.id); timeline.name = '验收子时间轴';
insertTimelineAction(project, timeline, { kind: 'background', assetId: 'qa_picture', transition: 'none' }, 0);
const keep = createTimelinePreset(project, '验收独立时间轴'); keep.id = 'qa_keep'; addProjectGraphs(project, keep);
project.contentBrowser = { folders: [{ id: 'qa_root', name: '验收目录' }, { id: 'qa_child', name: '验收子目录', parentId: 'qa_root' }], assignments: { 'blueprint:qa_owner': 'qa_root', ['timeline:' + timeline.id]: 'qa_child', 'asset:qa_picture': 'qa_child' }, favorites: [] };
project.scriptText = currentScriptText(projectToText(project));
await fs.writeFile(projectFile, JSON.stringify(project, null, 2));
const saved = async () => projectSchema.parse(JSON.parse(await fs.readFile(projectFile, 'utf8')));
const server = installedExecutable ? undefined : await createServer({ root, server: { host: '127.0.0.1', port: 0, watch: { ignored: ['**/artifacts/**', '**/resources/**', '**/release/**', '**/work/**'] } } });
await server?.listen();
let app: ElectronApplication | undefined, page: Page | undefined, phase = 'launch';
const errors: string[] = [], checks: string[] = [], layout: unknown[] = [];
try {
  app = await launchDesktopFixture({ root, projectFile, profile: path.join(output, 'profile'), devUrl: server ? 'http://127.0.0.1:' + (server.httpServer!.address() as { port: number }).port : undefined });
  page = await app.firstWindow(); page.on('pageerror', error => errors.push(error.message));
  await app.evaluate(({ BrowserWindow }) => { const window = BrowserWindow.getAllWindows()[0]; window.setContentSize(1380, 900); window.restore(); window.focus(); });
  await expect(page.locator('.project-title strong')).toHaveText(project.name, { timeout: 45000 });
  await page.locator('[data-workspace-tab="assets"]').click();
  const browser = page.getByRole('region', { name: '资源管理器' });
  const filter = browser.getByRole('button', { name: '类型筛选', exact: true });
  const scope = browser.getByLabel('资源显示范围', { exact: true });
  phase = 'single toolbar';
  for (const width of [1380, 1100]) {
    await app.evaluate(({ BrowserWindow }, width) => BrowserWindow.getAllWindows()[0].setContentSize(width, 900), width);
    const bounds = await browser.locator('.content-toolbar').evaluate(element => {
      const root = element.getBoundingClientRect();
      return { width: root.width, height: root.height, items: [...element.children].filter(child => getComputedStyle(child).display !== 'none').map(child => { const box = child.getBoundingClientRect(); return { x: box.x - root.x, right: box.right - root.x, y: box.y - root.y, bottom: box.bottom - root.y }; }) };
    });
    assert.ok(bounds.height <= 46, JSON.stringify(bounds));
    assert.ok(bounds.items.every(item => item.x >= 0 && item.right <= bounds.width + 1 && item.y >= 0 && item.bottom <= bounds.height + 1), JSON.stringify(bounds));
    layout.push(bounds);
  }
  await expect(browser.locator('.content-view-options')).toHaveCount(0);
  await scope.selectOption('all'); await filter.click();
  await browser.getByLabel('筛选时间轴预设', { exact: true }).check();
  await expect(browser.locator('.content-item.timeline')).toHaveCount(2);
  await expect(browser.locator('.content-item.blueprint')).toHaveCount(0);
  await browser.getByLabel('筛选蓝图', { exact: true }).check();
  await expect(browser.locator('.content-item.blueprint')).toHaveCount(1);
  await page.screenshot({ path: path.join(output, '01-toolbar-types.png') });
  await filter.click();
  checks.push('1100 / 1380 宽度工具栏单行且无溢出；蓝图和时间轴独立分类并可组合筛选。');

  phase = 'file confirmation and undo';
  await browser.locator('[data-content-key="timeline:qa_keep"]').click(); await page.keyboard.press('Delete');
  const dialog = page.getByRole('alertdialog', { name: '删除资源' });
  await expect(dialog).toContainText('1 项资源'); await expect(dialog.getByRole('button', { name: '取消', exact: true })).toBeFocused();
  await dialog.getByRole('button', { name: '取消', exact: true }).click();
  await expect(browser.locator('[data-content-key="timeline:qa_keep"]')).toHaveCount(1);
  await browser.locator('[data-content-key="timeline:qa_keep"]').click(); await page.keyboard.press('Delete');
  await dialog.getByRole('button', { name: '确认删除', exact: true }).click();
  await expect(browser.locator('[data-content-key="timeline:qa_keep"]')).toHaveCount(0);
  await page.keyboard.press('Control+z'); await expect(browser.locator('[data-content-key="timeline:qa_keep"]')).toHaveCount(1);
  checks.push('Delete 先确认，取消不更改资源，确认删除后可撤销恢复时间轴。');

  phase = 'recursive folder confirmation';
  await scope.selectOption('folder');
  await filter.click(); await browser.getByLabel('筛选时间轴预设', { exact: true }).uncheck(); await filter.click();
  await browser.locator('[data-content-key="folder:qa_root"]').click({ button: 'right' });
  await page.getByRole('menu', { name: '资源操作' }).getByRole('menuitem', { name: /^删除/ }).click();
  await expect(dialog).toContainText('3 项资源、2 个文件夹'); await expect(dialog).toContainText('验收隐藏图片');
  await page.screenshot({ path: path.join(output, '02-folder-confirmation.png') });
  await dialog.getByRole('button', { name: '确认删除', exact: true }).click();
  await expect(browser.locator('[data-content-key="folder:qa_root"]')).toHaveCount(0);
  await page.keyboard.press('Control+s');
  await expect.poll(async () => (await saved()).assets.length).toBe(0);
  const deleted = await saved(); assert.equal(deleted.blueprints.length, 0); assert.deepEqual(deleted.timelinePresets?.map(graph => graph.id), [keep.id]);
  assert.equal(deleted.contentBrowser?.folders.some(folder => ['qa_root', 'qa_child'].includes(folder.id)), false);
  await page.keyboard.press('Control+z');
  await expect(browser.locator('[data-content-key="folder:qa_root"]')).toHaveCount(1);
  await filter.click(); await browser.getByRole('button', { name: '显示全部类型' }).click(); await filter.click();
  await browser.locator('[data-content-key="folder:qa_root"]').dblclick(); await browser.locator('[data-content-key="folder:qa_child"]').dblclick();
  await browser.getByRole('button', { name: '删除文件夹及全部内容', exact: true }).click();
  await expect(dialog).toContainText('2 项资源、1 个文件夹');
  await dialog.getByRole('button', { name: '确认删除', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('仍被'); await dialog.getByRole('button', { name: '取消', exact: true }).click();
  await expect(browser.locator('.content-items [data-content-key]')).toHaveCount(2);
  checks.push('右键删除递归包含筛选隐藏项；保存后内部资源未被移到上级；面包屑删除也确认，外部引用阻止整批删除。');

  phase = 'timeline creation and reopen';
  await browser.locator('.content-breadcrumb').getByRole('button', { name: '项目资源', exact: true }).click();
  await browser.getByRole('button', { name: '新建', exact: true }).click();
  await browser.getByRole('button', { name: '时间轴预设', exact: true }).click();
  await expect(page.locator('.performance-workspace > .workspace-toolbar > strong')).toHaveText('时间轴预设');
  await page.keyboard.press('Control+s');
  await expect.poll(async () => (await saved()).timelinePresets?.length).toBe(3);
  const created = (await saved()).timelinePresets!.find(graph => graph.id !== timeline.id && graph.id !== keep.id)!;
  assert.ok(!project.blueprints.some(graph => graph.id === created.id));
  await page.screenshot({ path: path.join(output, '03-timeline-preset.png') });
  await page.reload(); await enterFixtureProject(page, projectFile);
  await expect(page.locator('.project-title strong')).toHaveText(project.name, { timeout: 45000 });
  await page.locator('[data-workspace-tab="assets"]').click();
  await scope.selectOption('all');
  await browser.locator(`[data-content-key="timeline:${created.id}"]`).dblclick();
  await expect(page.locator('.performance-workspace > .workspace-toolbar > strong')).toHaveText('时间轴预设');
  const reloaded = await saved(); assert.equal(reloaded.blueprints.length, 1); assert.equal(projectGraphs(reloaded).length, 4);
  checks.push('新建时间轴进入独立预设编辑器，保存到 timelinePresets；重开后类型、节点和引用保持。');

  phase = 'timeline drag and resource dock';
  await page.getByLabel('演出目标', { exact: true }).selectOption('graph:qa_owner');
  await expect(page.getByLabel('演出目标', { exact: true }).locator('optgroup[label="蓝图"] option')).toHaveCount(1);
  await expect(page.getByLabel('演出目标', { exact: true }).locator('optgroup[label="时间轴预设"] option')).toHaveCount(3);
  await page.keyboard.press('Control+Space');
  const dock = page.locator('.content-dock');
  await expect(dock).toBeVisible();
  await dock.getByLabel('资源显示范围', { exact: true }).selectOption('all');
  const beforeFilter = await dock.locator('.content-items').boundingBox(); assert.ok(beforeFilter);
  await dock.getByRole('button', { name: '类型筛选', exact: true }).click();
  await dock.getByLabel('筛选时间轴预设', { exact: true }).check();
  const afterFilter = await dock.locator('.content-items').boundingBox(); assert.ok(afterFilter);
  assert.equal(afterFilter.y, beforeFilter.y); assert.equal(afterFilter.height, beforeFilter.height);
  const popover = await dock.getByRole('group', { name: '资源类型筛选（可多选）' }).boundingBox();
  const toolbar = await dock.locator('.content-toolbar').boundingBox(); assert.ok(popover && toolbar);
  assert.ok(popover.y >= 0 && popover.y + popover.height <= toolbar.y + 1);
  await page.screenshot({ path: path.join(output, '04-dock-filters.png') });
  await dock.getByRole('button', { name: '类型筛选', exact: true }).click();
  await dock.locator('[data-content-key="timeline:qa_keep"]').dragTo(page.locator('.generic-blueprint-workspace .flow-container'), { targetPosition: { x: 160, y: 100 } });
  await page.keyboard.press('Control+s');
  await expect.poll(async () => (await saved()).blueprints.find(graph => graph.id === owner.id)?.nodes.some(node => node.type === 'callFunction' && node.properties.graphId === keep.id)).toBe(true);
  await page.screenshot({ path: path.join(output, '05-timeline-call.png') });
  checks.push('演出选择器分组列出蓝图与时间轴；底部类型浮层不挤占资源区，时间轴可真实拖入蓝图生成调用节点并保存。');
  assert.deepEqual(errors, []);
  await fs.writeFile(path.join(output, 'report.json'), JSON.stringify({ status: 'passed', installedExecutable, projectFile, checks, layout, errors }, null, 2));
} catch (error) {
  await page?.screenshot({ path: path.join(output, 'failure.png') }).catch(() => {});
  await fs.writeFile(path.join(output, 'report.json'), JSON.stringify({ status: 'failed', phase, error: String(error), checks, layout, errors }, null, 2)); throw error;
} finally {
  await app?.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().forEach(window => window.destroy())).catch(() => {});
  await app?.close().catch(() => {}); await server?.close(); console.log(output);
}
