import { expect, type ElectronApplication, type Page } from '@playwright/test';
import { promises as fs, createReadStream } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { launchDesktopFixture } from './lib/desktop-fixture';
import { openStoryMode } from './lib/story-workspace';
import { assetFiles, createProject, type Project } from '../src/core/model';
import { autosaveProject } from '../src/desktop/project-store';

const root = path.resolve('.'), output = path.join(root, 'artifacts/template-library', new Date().toISOString().replaceAll(':', '-'));
const profile = path.join(output, 'profile'), projects = path.join(output, 'projects');
await fs.mkdir(projects, { recursive: true });
const preservedDraft = path.join(profile, 'draft.vns.json');
await autosaveProject(preservedDraft, createProject('另一份未保存的工程'));
let app: ElectronApplication | undefined, page!: Page, phase = 'startup';
const checks: string[] = [], errors: string[] = [];
const read = async (file: string): Promise<Project> => JSON.parse(await fs.readFile(file, 'utf8'));
const digest = async (file: string) => { const hash = createHash('sha256'); for await (const data of createReadStream(file)) hash.update(data); return hash.digest('hex'); };
const launch = async () => {
  app = await launchDesktopFixture({ root, profile, projectHub: true });
  page = await app.firstWindow(); page.on('pageerror', error => errors.push(error.message));
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1440, 900));
  await expect(page.getByRole('main', { name: '项目窗口' })).toBeVisible({ timeout: 30000 });
};
const card = (name: string) => page.getByRole('article', { name: `模板 ${name}`, exact: true });
const hub = async () => page.evaluate(() => window.studio!.getProjectHub!());
const current = async () => page.evaluate(() => window.studio!.getInitial());
const editText = async (line: string) => {
  await openStoryMode(page, 'text');
  await page.getByLabel('中文文本剧本', { exact: true }).fill(`# 章节：模板章节\n# 小章节：开场\n@开始\n# 段落：第一幕\n旁白：${line}`);
};
const back = async () => {
  await page.getByRole('button', { name: '保存并返回模板库', exact: true }).click();
  await expect(page.getByRole('heading', { name: '管理你的模板' })).toBeVisible();
};
const createGame = async (template: string, name: string) => {
  await page.getByRole('button', { name: '新建项目', exact: true }).click();
  await page.getByRole('group', { name: '选择项目模板' }).getByRole('button').filter({ has: page.getByText(template, { exact: true }) }).click();
  await page.getByLabel('新项目名称', { exact: true }).fill(name);
  await page.getByLabel('新项目保存位置', { exact: true }).fill(projects);
  await page.getByRole('button', { name: '创建并打开项目', exact: true }).click();
  await expect(page.locator('.project-title strong')).toHaveText(name, { timeout: 90000 });
  await expect(page.locator('.project-browser')).toHaveCount(0);
  return path.join(projects, name, 'project.vns.json');
};
const changeSetting = async (label: string, value: string) => {
  await page.getByRole('button', { name: '作品设置', exact: true }).click();
  await page.getByRole('dialog', { name: '作品设置', exact: true }).getByLabel(label, { exact: true }).fill(value);
  await page.getByRole('button', { name: '完成', exact: true }).click();
};
try {
  await launch();
  expect((await hub()).templates.map(item => item.id)).toEqual(['aihong']);
  await expect(page.getByText(/分支入门/)).toHaveCount(0);
  await page.getByRole('button', { name: '模板库', exact: true }).click();
  await expect(card('哀鸿模板')).toBeVisible();
  await page.getByRole('button', { name: '新建模板', exact: true }).click();
  await page.getByLabel('模板名称', { exact: true }).fill('基础对白模板');
  await page.getByRole('button', { name: '创建并编辑模板', exact: true }).click();
  await expect(page.locator('.template-editing-badge')).toHaveText('模板编辑');
  await expect(page.locator('.template-editing-badge')).toBeVisible();
  const original = await current(); expect(original.template).toBeTruthy();
  expect(original.project.assets).toHaveLength(0);
  phase = 'edit custom template';
  await editText('这是模板中的开场。');
  await page.getByRole('button', { name: '保存模板', exact: true }).click();
  await expect(page.locator('.dirty-dot')).toHaveCount(0);
  expect((await read(original.path!)).scriptText!.content).toContain('这是模板中的开场。');
  await back();
  await expect(card('基础对白模板')).toBeVisible();
  expect((await hub()).recent).toHaveLength(0);
  await card('基础对白模板').getByRole('button', { name: '复制模板', exact: true }).click();
  await page.getByLabel('模板名称', { exact: true }).fill('对白模板副本');
  await page.getByRole('button', { name: '创建并编辑模板', exact: true }).click();
  await expect(page.locator('.project-title strong')).toHaveText('对白模板副本');
  const copy = await current(); expect(copy.project.id).not.toBe(original.project.id);
  await editText('这是副本独有的内容。');
  // Return action also saves pending editor changes.
  await back();
  expect((await read(copy.path!)).scriptText!.content).toContain('这是副本独有的内容。');
  expect((await read(original.path!)).scriptText!.content).not.toContain('副本独有');
  await fs.access(preservedDraft + '.autosave');
  checks.push('新建、编辑、保存、复制及保存并返回；副本内容独立，模板不进入最近项目');

  phase = 'reopen and rename';
  await card('对白模板副本').getByRole('button', { name: '打开编辑', exact: true }).click();
  await expect(page.locator('.project-title strong')).toHaveText('对白模板副本');
  await changeSetting('作品名称', '改名的对白模板');
  await back();
  await expect(card('改名的对白模板')).toBeVisible();
  await page.screenshot({ path: path.join(output, 'template-library.png') });
  await app!.close(); await launch();
  await page.getByRole('button', { name: '模板库', exact: true }).click();
  await expect(card('改名的对白模板')).toBeVisible();
  const gameFile = await createGame('改名的对白模板', '从自制模板创建');
  const game = await read(gameFile);
  expect(game.scriptText!.content).toContain('这是副本独有的内容。');
  expect(game.id).not.toBe(copy.project.id);
  await expect(page.locator('.template-editing-badge')).toHaveCount(0);
  await editText('仅属于新项目的内容。');
  await page.getByRole('button', { name: '项目窗口', exact: true }).click();
  await expect(page.locator('.recent-project-open').filter({ hasText: '从自制模板创建' })).toBeVisible();
  expect((await read(copy.path!)).scriptText!.content).toContain('这是副本独有的内容。');
  checks.push('改名与模板列表重启保留；自制模板可新建独立工程，修改工程不会回写模板');

  phase = 'built-in editing and assets';
  const builtinFile = path.join(root, 'resources/templates/aihong/project.vns.json'), builtinBefore = await digest(builtinFile);
  await page.getByRole('button', { name: '模板库', exact: true }).click();
  await card('哀鸿模板').getByRole('button', { name: '打开编辑', exact: true }).click();
  await expect(page.locator('.template-editing-badge')).toBeVisible({ timeout: 90000 });
  const builtin = await current(); expect(builtin.path).toContain(path.join(profile, 'templates', 'aihong'));
  await changeSetting('版本', '2.3.4');
  await page.screenshot({ path: path.join(output, 'template-editor.png') });
  await back();
  await expect(card('哀鸿模板')).toContainText('已在本机修改');
  expect(await digest(builtinFile)).toBe(builtinBefore);
  const builtinGameFile = await createGame('哀鸿模板', '使用编辑后的哀鸿');
  const builtinGame = await read(builtinGameFile);
  expect(builtinGame.version).toBe('2.3.4'); expect(builtinGame.assets.length).toBeGreaterThan(100);
  for (const asset of builtinGame.assets) for (const file of assetFiles(asset)) await fs.access(path.join(path.dirname(builtinGameFile), file));
  const asset = builtinGame.assets[0], sourceAsset = builtin.project.assets.find(item => item.id === asset.id)!;
  expect(await digest(path.join(path.dirname(builtinGameFile), asset.path))).toBe(await digest(path.join(path.dirname(builtin.path!), sourceAsset.path)));
  expect(await digest(builtinFile)).toBe(builtinBefore);
  checks.push('哀鸿模板本机编辑生效，程序自带模板未改变，新建游戏的全部素材可读取');

  phase = 'existing editor creation entry';
  await page.getByRole('button', { name: '新建工程', exact: true }).click();
  await expect(page.getByLabel('工程模板', { exact: true }).locator('option[value=branching]')).toHaveCount(0);
  await page.getByLabel('工程模板', { exact: true }).selectOption(copy.template!.id);
  await page.getByLabel('作品名称', { exact: true }).fill('编辑器内从模板创建');
  const editorGameFile = path.join(projects, '编辑器内创建', 'project.vns.json');
  await app!.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }); }, editorGameFile);
  await page.getByRole('button', { name: '创建作品', exact: true }).click();
  await expect(page.locator('.project-title strong')).toHaveText('编辑器内从模板创建');
  expect((await read(editorGameFile)).scriptText!.content).toContain('这是副本独有的内容。');
  await fs.access(preservedDraft + '.autosave');
  await page.getByRole('button', { name: '项目窗口', exact: true }).click();
  await page.getByRole('button', { name: '模板库', exact: true }).click();
  await app!.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1024, 700));
  expect(await page.locator('.project-browser-content').evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  await page.screenshot({ path: path.join(output, 'template-library-small.png') });
  checks.push('编辑器内新建入口也可使用自制模板；分支入门已移除；小窗口布局正常');
  expect(errors).toEqual([]);
  await fs.writeFile(path.join(output, 'result.json'), JSON.stringify({ status: 'passed', checks, errors }, null, 2));
  console.log(JSON.stringify({ output, checks }, null, 2));
} catch (error) {
  await page?.screenshot({ path: path.join(output, 'failure.png') }).catch(() => undefined);
  await fs.writeFile(path.join(output, 'failure.txt'), `${phase}\n${String(error)}\n${errors.join('\n')}`);
  console.error('Failed:', phase, output); throw error;
} finally { await app?.close().catch(() => undefined); }
