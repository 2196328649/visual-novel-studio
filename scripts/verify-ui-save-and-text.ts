  await expect(page.locator('.ui-component', { hasText: '页面切换保存' })).toHaveCount(1);
  await expect(page.locator('.ui-component', { hasText: '窗口关闭取消' })).toHaveCount(0);
  await openStoryMode(page, 'text');
  await expect(page.getByLabel('文本章节', { exact: true })).toHaveCount(0);
  await expect(page.locator('.text-editor-toolbar').getByRole('button', { name: '插入指令', exact: true })).toHaveCount(0);
  const hide = page.locator('.text-panel-heading').getByRole('button', { name: '隐藏演出', exact: true });
  await expect(hide).toBeVisible();
  if (await hide.getAttribute('aria-pressed') === 'true') await hide.click();
  const input = page.getByLabel('中文文本剧本', { exact: true });
  const point = await input.evaluate(element => {
    const field = element as HTMLTextAreaElement, lines = field.value.split('\n');
    const index = lines.findIndex(line => line.includes('@等待'));
    if (index < 0) throw new Error('缺少等待指令：' + field.value);
    const style = getComputedStyle(field), lineHeight = parseFloat(style.lineHeight);
    field.scrollTop = Math.max(0, index * lineHeight - 80);
    const bounds = field.getBoundingClientRect();
    return { x: bounds.x + parseFloat(style.paddingLeft) + 55, y: bounds.y + parseFloat(style.paddingTop) + (index + .5) * lineHeight - field.scrollTop };
  });
  await page.mouse.click(point.x, point.y);
