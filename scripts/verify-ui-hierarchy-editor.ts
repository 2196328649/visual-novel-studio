import assert from 'node:assert/strict';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { expect } from '@playwright/test';
import { createServer } from 'vite';
import { uiHierarchyFixture } from './lib/ui-hierarchy-fixture';
import { launchDesktopFixture, installedExecutable, enterFixtureProject } from './lib/desktop-fixture';
import { openUiPreviewWindow } from './lib/ui-preview-window';
import { openStoryMode } from './lib/story-workspace';
import { applyTextScript } from '../src/core/text-script';
import { projectSchema, type Project } from '../src/core/model';

const root = path.resolve('.'), output = path.join(root, 'artifacts/ui-hierarchy-editor', new Date().toISOString().replaceAll(':', '-'));
const { project, projectFile, entries } = await uiHierarchyFixture(path.join(output, 'project'));
const server = installedExecutable ? undefined : await createServer({ root, server: { host: '127.0.0.1', port: 0, watch: { ignored: ['**/artifacts/**', '**/resources/**', '**/release/**', '**/work/**'] } } });
await server?.listen();
const app = await launchDesktopFixture({ root, projectFile, profile: path.join(output, 'profile'), devUrl: server ? 'http://127.0.0.1:' + (server.httpServer!.address() as { port: number }).port : undefined });
const page = await app.firstWindow(), errors: string[] = [], checks: string[] = [];
page.on('pageerror', error => errors.push(error.message));
const row = (id: string) => page.locator(`[data-hierarchy-id="${id}"]`);
const object = (id: string) => page.locator(`.ui-canvas [data-component-id="${id}"]`);
const saved = async () => projectSchema.parse(JSON.parse(await fs.readFile(projectFile, 'utf8')));
let phase = 'launch';
const openChildren = async () => { const panel = page.locator('.ui-child-objects'); if (await panel.getAttribute('open') === null) await panel.locator(':scope > summary').click(); };
try {
  await expect(page.locator('.project-title strong')).toHaveText(project.name, { timeout: 45000 });
  await app.evaluate(({ BrowserWindow }) => { const w = BrowserWindow.getAllWindows()[0]; w.setContentSize(1600, 1000); });
  await page.locator('[data-workspace-tab="ui"]').click();
  phase = 'hierarchy';
  await expect(row('ornament')).toHaveAttribute('aria-level', '4');
  await row('memory_button').click();
  await openChildren();
  await expect(page.getByRole('list', { name: '子对象列表' })).toContainText('记忆背景');
  const initialBox = (await object('memory_button').boundingBox())!;
  await page.getByLabel('宽度 %', { exact: true }).fill('35'); await page.keyboard.press('Tab');
  await expect.poll(async () => (await object('button_background').boundingBox())!.width).toBeGreaterThan(initialBox.width * 1.45);
  const parentBefore = (await object('memory_button').boundingBox())!, childBefore = (await object('button_background').boundingBox())!;
  await page.mouse.move(parentBefore.x + parentBefore.width * .5, parentBefore.y + parentBefore.height * .5); await page.mouse.down();
  await page.mouse.move(parentBefore.x + parentBefore.width * .5 + 35, parentBefore.y + parentBefore.height * .5 + 18, { steps: 5 }); await page.mouse.up();
  await expect.poll(async () => (await object('button_background').boundingBox())!.x - childBefore.x).toBeGreaterThan(25);
  checks.push('父级宽度调整与画布拖动同步影响子图');
  await row('button_background').click();
  await page.getByLabel('相对父级横向位置 %', { exact: true }).fill('8'); await page.keyboard.press('Tab');
  const parent = (await object('memory_button').boundingBox())!, child = (await object('button_background').boundingBox())!;
  assert.ok(Math.abs(child.x - (parent.x + parent.width * .08)) < 2);
  phase = 'reparent';
  await page.getByLabel('父对象', { exact: true }).selectOption('');
  let detached = (await object('button_background').boundingBox())!; assert.ok(Math.abs(detached.x - child.x) < 2 && Math.abs(detached.width - child.width) < 2);
  await openChildren(); await page.getByLabel('父对象', { exact: true }).selectOption('memory_button');
  detached = (await object('button_background').boundingBox())!; assert.ok(Math.abs(detached.x - child.x) < 2);
  await expect(row('ornament')).toHaveAttribute('aria-level', '4');
  checks.push('解除和重设父级保留视觉位置与完整子树');
  phase = 'add-copy-delete';
  const spareSkin = await object('spare_button').locator('img').first().getAttribute('src');
  await row('spare_button').click(); await openChildren(); await page.getByRole('button', { name: '添加背景子图', exact: true }).click();
  await expect(page.getByLabel('父对象', { exact: true })).toHaveValue('spare_button');
  await page.getByLabel('控件显示名称', { exact: true }).fill('备用背景');
  const added = await page.locator('.ui-hierarchy-row.selected').getAttribute('data-hierarchy-id'); assert.ok(added);
  await expect(object('spare_button').locator('img').first()).toHaveAttribute('src', spareSkin!);
  await expect(object(added).locator('img')).toHaveCount(0);
  await row('spare_button').click(); await openChildren(); await page.getByRole('button', { name: '添加子图片', exact: true }).click();
  await expect(page.getByLabel('父对象', { exact: true })).toHaveValue('spare_button');
  await expect(page.getByLabel('子对象放置位置', { exact: true })).toHaveValue('foreground');
  await expect(object('spare_button').locator('img').first()).toHaveAttribute('src', spareSkin!);
  const count = await page.locator('[data-hierarchy-id]').count();
  await row('memory_button').click(); await openChildren(); await page.getByRole('button', { name: '复制组件及子对象', exact: true }).click();
  await expect(page.locator('[data-hierarchy-id]')).toHaveCount(count + 3);
  await page.getByRole('button', { name: '撤销', exact: true }).click(); await expect(page.locator('[data-hierarchy-id]')).toHaveCount(count);
  await page.getByRole('button', { name: '重做', exact: true }).click(); await expect(page.locator('[data-hierarchy-id]')).toHaveCount(count + 3);
  await page.getByRole('button', { name: '删除组件', exact: true }).click(); await expect(page.locator('[data-hierarchy-id]')).toHaveCount(count);
  await page.getByRole('button', { name: '撤销', exact: true }).click(); await expect(page.locator('[data-hierarchy-id]')).toHaveCount(count + 3);
  await page.getByRole('button', { name: '重做', exact: true }).click(); await expect(page.locator('[data-hierarchy-id]')).toHaveCount(count);
  await row('memory_button').click(); await page.screenshot({ path: path.join(output, 'hierarchy.png') });
  await page.getByRole('button', { name: '保存界面', exact: true }).click(); await expect(page.locator('.dirty-dot')).toHaveCount(0);
  assert.equal((await saved()).ui.components.find(c => c.id === added)!.parentId, 'spare_button');
  checks.push('添加背景、复制和删除完整子树、撤销重做及保存');
  phase = 'interactive-preview';
  const preview = await openUiPreviewWindow(app, page); preview.on('pageerror', error => errors.push(error.message));
  const backgroundImage = preview.locator('[data-preview-component="button_background"] img').first(), idleSource = await backgroundImage.getAttribute('src');
  const previewButton = preview.getByRole('button', { name: '记忆浮现', exact: true });
  await previewButton.hover(); await expect(backgroundImage).not.toHaveAttribute('src', idleSource!);
  await previewButton.click(); await expect(preview.locator('[data-preview-component="trace"]')).toHaveText('已点击一次');
  await preview.screenshot({ path: path.join(output, 'interactive-preview.png') });
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().filter(w => w.webContents.getURL().endsWith('#ui-preview')).forEach(w => w.close()));
  checks.push('独立预览窗口子图跟随悬停，背景不遮挡按钮点击');
  phase = 'flow-style-editor';
  await page.getByLabel('设计页面', { exact: true }).selectOption('flowchart'); await row('flow').click();
  await page.getByText('流程图框样式', { exact: true }).click();
  await expect(page.getByLabel('编辑框样式', { exact: true })).toBeVisible();
  await page.getByLabel('编辑框样式', { exact: true }).selectOption('main_style');
  await page.getByLabel('样式名称', { exact: true }).fill('主线新框');
  await page.getByText('文字、边框和阴影', { exact: true }).click();
  await page.getByLabel('框样式阴影浓度', { exact: true }).fill('30'); await page.keyboard.press('Tab');
  await page.getByRole('button', { name: '新建框样式', exact: true }).click(); await page.getByLabel('样式名称', { exact: true }).fill('备用框');
  await page.getByRole('button', { name: '保存界面', exact: true }).click(); await expect(page.locator('.dirty-dot')).toHaveCount(0);
  const current = await saved(); assert.equal(current.ui.flowStyles?.find(s => s.id === 'main_style')?.style?.shadowOpacity, .3);
  assert.ok(current.scriptText!.content.includes('主线新框【main_style】')); assert.ok(current.ui.flowStyles?.some(s => s.name === '备用框'));
  await page.locator('.ui-canvas').screenshot({ path: path.join(output, 'flow-preview.png') });
  await page.screenshot({ path: path.join(output, 'flow-style-editor.png') });
  checks.push('框样式创建、重命名、阴影调整与所有引用同步');
  phase = 'completion';
  await openStoryMode(page, 'text');
  const input = page.getByLabel('中文文本剧本', { exact: true });
  await input.evaluate(element => { const t = element as HTMLTextAreaElement, start = t.value.indexOf('样式='); if (start < 0) throw new Error('missing style'); t.focus(); t.setSelectionRange(start + 3, start + 3); t.dispatchEvent(new Event('select', { bubbles: true })); });
  await page.keyboard.press('Control+Space');
  const menu = page.getByRole('listbox', { name: '文本补全建议' }); await expect(menu).toBeVisible(); await expect(menu).toContainText('主线新框'); await expect(menu).toContainText('备用框');
  await page.keyboard.press('Escape');
  assert.deepEqual(applyTextScript(current, current.scriptText!.content).issues.filter(d => d.severity === 'error'), []);
  checks.push('章节样式参数提示与补全');
  phase = 'reopen';
  await page.reload(); await enterFixtureProject(page, projectFile); await expect(page.locator('.project-title strong')).toHaveText(project.name);
  await page.locator('[data-workspace-tab="ui"]').click(); await page.getByLabel('设计页面', { exact: true }).selectOption('main');
  await expect(row(added)).toHaveAttribute('data-parent-id', 'spare_button'); await expect(row('ornament')).toHaveAttribute('aria-level', '4');
  await row('memory_button').click(); await expect(page.getByLabel('宽度 %', { exact: true })).toHaveValue('35');
  assert.deepEqual(errors, []); checks.push('重新打开保留父子关系、尺寸和样式，渲染无报错');
  await fs.writeFile(path.join(output, 'report.json'), JSON.stringify({ status: 'passed', checks, entries, projectFile, errors }, null, 2)); console.log(output);
} catch (error) {
  await page.screenshot({ path: path.join(output, 'failure.png') }).catch(() => undefined);
  await fs.writeFile(path.join(output, 'report.json'), JSON.stringify({ status: 'failed', phase, checks, errors, error: String(error) }, null, 2)); console.log(output); throw error;
} finally {
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().forEach(w => w.destroy())).catch(() => undefined); await app.close(); await server?.close();
}
