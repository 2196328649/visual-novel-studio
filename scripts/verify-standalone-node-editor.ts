import assert from 'node:assert/strict';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { expect, type ElectronApplication, type Page } from '@playwright/test';
import { launchDesktopFixture } from './lib/desktop-fixture';
import { openStoryMode } from './lib/story-workspace';
import { projectSchema } from '../src/core/model';
import { applyTextScript } from '../src/core/text-script';
import { isStandaloneNode } from '../src/core/standalone-performance';
import { performanceTimeline } from '../src/core/performance-timeline';

const root = path.resolve('.'), output = path.join(root, 'artifacts/standalone-node-editor', new Date().toISOString().replaceAll(':', '-'));
const projectDirectory = path.join(output, 'project'), projectFile = path.join(projectDirectory, 'project.vns.json');
await fs.cp(path.join(root, 'resources/templates/aihong'), projectDirectory, { recursive: true });
const original = projectSchema.parse(JSON.parse(await fs.readFile(projectFile, 'utf8')));
let app: ElectronApplication | undefined, page: Page | undefined;
const errors: string[] = [], checks: string[] = [];
const launch = async () => {
  app = await launchDesktopFixture({ root, profile: path.join(output, 'profile'), projectFile });
  page = await app.firstWindow();
  page.on('pageerror', error => errors.push(error.message));
  await app.evaluate(({ BrowserWindow, screen }) => {
    const window = BrowserWindow.getAllWindows()[0];
    const secondary = screen.getAllDisplays().find(display => display.id !== screen.getPrimaryDisplay().id);
    if (secondary) window.setPosition(secondary.workArea.x + 10, secondary.workArea.y + 10);
    window.setContentSize(1520, 980);
  });
  await expect(page.locator('.project-title strong')).toHaveText(original.name, { timeout: 45_000 });
};
try {
  await launch();
  await openStoryMode(page!, 'script');
  const start = page!.locator('#node-start');
  await start.getByRole('button', { name: '编辑剧情节点', exact: true }).click();
  const inspector = start.locator('.inspector');
  await expect(inspector).toContainText('名称');
  await expect(inspector.getByLabel('接下来', { exact: true })).toBeVisible();
  await expect(inspector).not.toContainText('所属场景');
  await expect(inspector).not.toContainText('场景实例');
  await expect(inspector.getByRole('button', { name: '管理效果', exact: true })).toHaveCount(0);
  await expect(inspector.getByRole('button', { name: '复制', exact: true })).toHaveCount(0);
  await page!.screenshot({ path: path.join(output, '01-start-simplified.png') });
  checks.push('流程起点仅保留名称和后续连接，移除场景参数、效果管理及复制删除');
  const chapter = page!.locator('#node-ai_title_one');
  await expect(chapter).toHaveAttribute('data-node-kind', 'standalone');
  await expect(chapter).toContainText('7 秒');
  await expect(chapter).toContainText('花街柳巷');
  await chapter.scrollIntoViewIfNeeded();
  await page!.screenshot({ path: path.join(output, '02-standalone-card.png') });
  await chapter.getByRole('button', { name: '编辑独立演出', exact: true }).click();
  await expect(page!.getByLabel('演出用途', { exact: true })).toHaveValue('standalone');
  await expect(page!.getByRole('button', { name: '转为可编辑演出', exact: true })).toHaveCount(0);
  await expect(page!.locator('.timeline-clip')).toHaveCount(1);
  await expect(page!.locator('.timeline-clip')).toContainText('7.00s');
  await expect(page!.getByLabel('对话界面预览', { exact: true })).toHaveCount(0);
  await page!.locator('.timeline-clip').click();
  const duration = page!.locator('.timeline-parameter').filter({ has: page!.getByText('时长', { exact: true }) }).locator('input');
  await duration.fill('8'); await duration.press('Tab');
  await expect(page!.locator('.timeline-clip')).toContainText('8.00s');
  await duration.fill('7'); await duration.press('Tab');
  await expect(page!.locator('.timeline-clip')).toContainText('7.00s');
  await page!.getByRole('button', { name: '适合窗口', exact: true }).click();
  await page!.locator('.timeline-inspector').evaluate(element => { element.scrollTop = 0; });
  await page!.screenshot({ path: path.join(output, '03-independent-timeline.png') });
  checks.push('章节卡片直接进入可编辑时间轴，修改时长立即生效');
  for (const [width, height] of [[1024, 680], [1280, 720]]) {
    await app!.evaluate(({ BrowserWindow }, size) => BrowserWindow.getAllWindows()[0].setContentSize(size[0], size[1]), [width, height]);
    await page!.locator('.timeline-inspector .timeline-parameter button').last().scrollIntoViewIfNeeded();
    await expect.poll(() => page!.locator('.performance-timeline').evaluate(element => element.scrollHeight - element.clientHeight)).toBeLessThanOrEqual(2);
    const track = await page!.locator('.timeline-scroll').boundingBox();
    assert.ok(track && track.height >= 130 && track.y + track.height <= height - 20);
    await page!.screenshot({ path: path.join(output, `timeline-${width}.png`) });
  }
  checks.push('1024×680、1280×720 下时间轴和底部参数均可完整到达');
  await app!.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1520, 980));
  await page!.getByRole('button', { name: '保存工程', exact: true }).click();
  await expect(page!.locator('.dirty-dot')).toHaveCount(0);
  const saved = projectSchema.parse(JSON.parse(await fs.readFile(projectFile, 'utf8')));
  const savedChapter = saved.nodes.find(node => node.id === 'ai_title_one');
  assert.ok(isStandaloneNode(savedChapter));
  assert.equal(savedChapter.next, 'opening');
  const action = savedChapter.lines[0].actions[0];
  assert.equal(action.kind, 'blueprint');
  assert.ok(action.kind === 'blueprint');
  const graph = saved.blueprints.find(graph => graph.id === action.blueprintId)!;
  assert.equal(graph.performanceKind, 'standalone');
  assert.equal(performanceTimeline(saved, graph).until, 7);
  const properties = graph.nodes.find(node => node.type === 'showChapter')!.properties;
  assert.equal(properties.title, '第一章 · 酒醒城破');
  assert.equal(properties.backgroundId, 'ai_presentation_chapter_one');
  assert.equal(properties.titleImageId, 'ai_presentation_title_one');
  assert.equal(properties.musicId, 'ai_story_music_wine');
  assert.equal(saved.nodes.length, original.nodes.length);
  const reparsed = applyTextScript(saved, saved.scriptText!.content);
  assert.deepEqual(reparsed.issues, []);
  assert.deepEqual(JSON.parse(JSON.stringify(reparsed.project.nodes)), JSON.parse(JSON.stringify(saved.nodes)));
  await app!.close(); app = undefined;
  await launch();
  await openStoryMode(page!, 'script');
  await page!.locator('#node-ai_title_one').getByRole('button', { name: '编辑独立演出', exact: true }).click();
  await expect(page!.locator('.timeline-clip')).toContainText('7.00s');
  await page!.getByRole('button', { name: '保存工程', exact: true }).click();
  await expect(page!.locator('.dirty-dot')).toHaveCount(0);
  const reopened = projectSchema.parse(JSON.parse(await fs.readFile(projectFile, 'utf8')));
  assert.equal(reopened.blueprints.length, saved.blueprints.length);
  checks.push('保存重开保留标题、背景、题图、配乐、七秒时长和连接，重复打开不生成重复蓝图');
  const another = reopened.nodes.find(node => isStandaloneNode(node) && node.id !== savedChapter.id)!;
  await page!.getByLabel('演出目标', { exact: true }).selectOption('node:' + another.id + '/');
  await expect(page!.getByLabel('演出用途', { exact: true })).toHaveValue('standalone');
  await expect(page!.locator('.timeline-clip')).toHaveCount(1);
  await expect(page!.getByRole('button', { name: '转为可编辑演出', exact: true })).toHaveCount(0);
  checks.push('蓝图目标列表中的章节同样直接打开时间轴');
  await page!.getByRole('button', { name: '保存工程', exact: true }).click();
  await expect(page!.locator('.dirty-dot')).toHaveCount(0);
  await page!.getByLabel('演出目标', { exact: true }).selectOption('node:ai_title_one/');
  await openStoryMode(page!, 'script');
  await page!.locator('#node-start').getByRole('button', { name: '编辑剧情节点', exact: true }).click();
  await page!.locator('#node-start').scrollIntoViewIfNeeded();
  assert.deepEqual(errors, []);
  await fs.writeFile(path.join(output, 'report.json'), JSON.stringify({ status: 'passed', checks, errors, projectFile }, null, 2));
  console.log(output);
  if (process.env.VNS_KEEP_REVIEW === '1') {
    console.log('开发版已留在副屏供查看。');
    await new Promise<void>(resolve => app!.process().once('exit', () => resolve()));
    app = undefined;
  }
} catch (error) {
  await page?.screenshot({ path: path.join(output, 'failure.png') }).catch(() => undefined);
  await fs.writeFile(path.join(output, 'failure.json'), JSON.stringify({ error: String(error), checks, errors }, null, 2));
  console.log(output);
  throw error;
} finally { await app?.close(); }
