import assert from 'node:assert/strict';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { expect, type Locator } from '@playwright/test';
import { createProject, projectSchema } from '../src/core/model';
import { assetSourcePath } from '../src/desktop/project-store';
import { applyTextScript } from '../src/core/text-script';
import { enterFixtureProject, launchDesktopFixture } from './lib/desktop-fixture';
import { openStoryMode } from './lib/story-workspace';
import { cleanVerificationDirectories } from './lib/verification-cleanup';

const root = path.resolve('.'), output = path.join(root, 'artifacts/display-text-editor', new Date().toISOString().replaceAll(':', '-'));
const directory = path.join(output, 'project'), projectFile = path.join(directory, 'project.vns.json');
await fs.mkdir(directory, { recursive: true });
const templateDir = path.join(root, 'resources/templates/aihong');
const template = projectSchema.parse(JSON.parse(await fs.readFile(path.join(templateDir, 'project.vns.json'), 'utf8')));
const font = template.assets.find(asset => asset.kind === 'font')!;
await fs.copyFile(assetSourcePath(templateDir, font), path.join(directory, 'font.ttf'));
const project = createProject('显示文字与台词分离验收');
project.assets.push({ id: 'test_font', name: '验收字体', kind: 'font', path: 'font.ttf' });
const node = project.nodes.find(node => node.kind === 'passage')!;
node.lines = [{ id: 'dialogue', text: '台词保持自己的颜色和速度。', actions: [{ kind: 'pause', seconds: .05 }],
  textPresentation: { color: '#ff5555', speed: 'cps', cps: 18 }, textSpans: [{ start: 0, end: 2, style: { bold: true } }] }];
await fs.writeFile(projectFile, JSON.stringify(project));
const app = await launchDesktopFixture({ root, projectFile, profile: path.join(output, 'profile') }), page = await app.firstWindow();
const errors: string[] = [], checks: string[] = []; let phase = 'module';
page.on('pageerror', error => errors.push(error.message));
const number = async (scope: Locator, label: string, value: string) => { const input = scope.getByLabel(label, { exact: true }); await input.fill(value); await input.press('Tab'); };
const save = async () => {
  await page.getByRole('button', { name: '保存工程', exact: true }).click();
  await expect(page.locator('.dirty-dot')).toHaveCount(0);
  return projectSchema.parse(JSON.parse(await fs.readFile(projectFile, 'utf8')));
};
const savedLine = async () => (await save()).nodes.flatMap(node => node.kind === 'passage' ? node.lines : []).find(line => line.id === 'dialogue')!;
const undo = () => page.getByRole('button', { name: '撤销', exact: true }).first().click();
try {
  await expect(page.locator('.project-title strong')).toHaveText(project.name, { timeout: 45000 });
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1600, 1050));
  await openStoryMode(page, 'script');
  const row = page.locator('#line-dialogue'), dialogue = row.getByLabel('第1行对白', { exact: true });
  const textPanel = row.getByRole('region', { name: '第1行台词文字演出', exact: true });
  await expect(textPanel).toHaveCount(0);
  await expect(row.locator('.line-effect-chip')).toHaveCount(1);
  await expect(row.locator('.line-expand > span')).toHaveText('2');
  const addText = async () => {
    await row.getByRole('button', { name: '为第1行添加效果', exact: true }).click();
    const menu = row.getByRole('menu', { name: '添加本行演出', exact: true });
    await expect(menu.getByRole('menuitem', { name: '显示文字', exact: true })).toHaveCount(1);
    await expect(menu.getByRole('menuitem', { name: /添加文字演出|^文字演出$/ })).toHaveCount(0);
    await menu.getByRole('menuitem', { name: '显示文字', exact: true }).click();
    return row.getByRole('region', { name: '编辑显示文字', exact: true });
  };
  let object = await addText();
  await object.getByLabel('对象文字', { exact: true }).fill('第一段浮空文字');
  await number(object, '文字纵向位置 %', '25');
  await number(object, '对象字号', '72');
  await number(object, '对象持续秒数', '4');
  await object.getByRole('button', { name: '浏览对象字体', exact: true }).click();
  await page.getByRole('dialog', { name: '对象字体资源浏览器', exact: true }).locator('.asset-picker-card').filter({ hasText: '验收字体' }).dblclick();
  await object.locator('summary').filter({ hasText: /^文字动画$/ }).click();
  await object.getByLabel('文字显示方式', { exact: true }).selectOption('duration');
  await number(object, '逐字显示时长（秒）', '1.2');
  await object.getByLabel('入场效果', { exact: true }).selectOption('drop');
  await object.getByLabel('持续效果', { exact: true }).selectOption('wave');
  await object.getByLabel('退场效果', { exact: true }).selectOption('fade');
  await object.getByRole('button', { name: '收起演出编辑', exact: true }).click();
  object = await addText();
  await object.getByLabel('对象文字', { exact: true }).fill('第二段普通文字');
  await number(object, '文字纵向位置 %', '48');
  await number(object, '对象字号', '36');
  await object.getByLabel('对象颜色', { exact: true }).fill('#66ccff');
  await object.getByRole('button', { name: '收起演出编辑', exact: true }).click();
  const withTexts = await savedLine(), texts = withTexts.actions.filter(action => action.kind === 'visual');
  assert.equal(texts.length, 2); assert.notEqual(texts[0].instanceId, texts[1].instanceId);
  assert.equal(texts[0].fontAssetId, 'test_font'); assert.equal(texts[0].textMotion?.duration, 1.2);
  assert.equal(texts[1].textMotion, undefined);
  assert.deepEqual(withTexts.textPresentation, node.lines[0].textPresentation);
  assert.deepEqual(withTexts.textSpans, node.lines[0].textSpans);
  await expect(row.locator('.line-expand > span')).toHaveText('2');
  const strip = (await row.locator('.line-effect-strip').boundingBox())!, box = (await dialogue.boundingBox())!;
  assert.ok(strip.y + strip.height <= box.y);
  const preview = page.locator('.story-preview-content');
  await number(preview, '定位演出时间（秒）', '1.5');
  for (const text of texts) await expect(preview.locator(`[data-visual-instance="${text.instanceId}"] [data-visual-text]`)).toHaveText(text.text);
  await expect(preview.locator(`[data-visual-instance="${texts[0].instanceId}"] [data-text-loop="wave"]`).first()).toBeVisible();
  await expect(preview.locator('.ui-dialogue-preview .styled-text').first()).toHaveCSS('color', 'rgb(255, 85, 85)');
  await page.screenshot({ path: path.join(output, 'two-texts-and-dialogue.png') });
  checks.push('台词上方可新增多段显示文字，自动分配不同 ID；字体、字号、位置和可选动画独立生效，预览同时保留台词');

  phase = 'independent edits';
  await row.getByRole('button', { name: '展开第1行台词文字演出', exact: true }).click();
  await expect(textPanel.getByRole('tab', { name: /^舞台演出|^配音$/ })).toHaveCount(0);
  const panelBox = (await textPanel.boundingBox())!, dialogueBox = (await dialogue.boundingBox())!;
  assert.ok(panelBox.y >= dialogueBox.y + dialogueBox.height);
  await textPanel.getByRole('button', { name: '删除文字演出', exact: true }).click();
  const cleared = await savedLine();
  assert.equal(cleared.textPresentation, undefined); assert.equal(cleared.textSpans?.length ?? 0, 0);
  assert.deepEqual(cleared.actions, withTexts.actions); await expect(row.locator('.line-expand > span')).toHaveCount(0);
  await undo(); assert.deepEqual((await savedLine()).textPresentation, withTexts.textPresentation);
  await row.getByRole('button', { name: '收起第1行台词文字演出', exact: true }).click();
  await row.getByRole('button', { name: '编辑显示文字：第二段普通文字', exact: true }).click();
  await row.getByRole('region', { name: '编辑显示文字', exact: true }).getByRole('button', { name: '删除动作', exact: true }).click();
  const removed = await savedLine();
  assert.equal(removed.actions.length, 2); assert.deepEqual(removed.actions[1], texts[0]);
  assert.deepEqual(removed.textPresentation, withTexts.textPresentation);
  await undo();
  await row.getByRole('button', { name: '编辑显示文字：第一段浮空文字', exact: true }).click();
  object = row.getByRole('region', { name: '编辑显示文字', exact: true });
  await object.getByRole('button', { name: '清除文字动画', exact: true }).click();
  const noMotion = (await savedLine()).actions[1]; assert.ok(noMotion.kind === 'visual');
  assert.equal(noMotion.textMotion, undefined); assert.equal(noMotion.text, texts[0].text); assert.equal(noMotion.fontAssetId, 'test_font');
  await undo();
  checks.push('台词箭头只管理台词；删除台词效果、删除单个浮空文字或清除动画均不影响其他内容，并可撤销');

  phase = 'text command picker';
  await openStoryMode(page, 'text');
  const input = page.getByLabel('中文文本剧本', { exact: true });
  const source = await input.inputValue();
  assert.equal((source.match(/@显示文字：/g) ?? []).length, 2); assert.doesNotMatch(source, /@演出实例|@添加文字演出/);
  const insertedIds: string[] = [];
  for (const animated of [true, false]) {
    await input.focus(); await input.press('Control+End'); await input.press('Enter'); await input.press('/');
    const palette = page.getByRole('dialog', { name: '中文指令面板', exact: true });
    await expect(palette.getByText('显示文字', { exact: true })).toHaveCount(1);
    await expect(palette.getByText('添加文字演出', { exact: true })).toHaveCount(0);
    await palette.getByText('显示文字', { exact: true }).click();
    const picker = page.getByRole('dialog', { name: '命令参数', exact: true });
    insertedIds.push(await picker.getByLabel('对象ID', { exact: true }).inputValue());
    await picker.getByLabel('显示文字内容', { exact: true }).fill(animated ? '指令里的动画文字' : '指令里的普通文字');
    if (animated) {
      await picker.getByRole('button', { name: '浏览文字字体', exact: true }).click();
      await page.getByRole('dialog', { name: '文字字体资源浏览器', exact: true }).locator('.asset-picker-card').filter({ hasText: '验收字体' }).dblclick();
      await picker.locator('summary').filter({ hasText: /^文字动画$/ }).click();
      await picker.getByLabel('持续效果', { exact: true }).selectOption('pulse');
      await expect(picker.getByLabel('文字显示方式', { exact: true })).toHaveValue('instant');
      await page.screenshot({ path: path.join(output, 'display-text-picker.png') });
    }
    await picker.getByRole('button', { name: '插入指令', exact: true }).click();
    await input.fill((await input.inputValue()) + '\n旁白：下一句。\n'); await input.press('Control+End');
  }
  assert.notEqual(insertedIds[0], insertedIds[1]);
  const saved = await save(), parsed = applyTextScript(saved, saved.scriptText!.content);
  assert.deepEqual(parsed.issues, []);
  const all = parsed.project.nodes.flatMap(node => node.kind === 'passage' ? node.lines.flatMap(line => line.actions) : []).filter(action => action.kind === 'visual');
  assert.equal(all.length, 4);
  assert.equal(all.find(item => item.instanceId === insertedIds[0])?.textMotion?.loop, 'pulse');
  assert.equal(all.find(item => item.instanceId === insertedIds[0])?.fontAssetId, 'test_font');
  assert.equal(all.find(item => item.instanceId === insertedIds[1])?.textMotion, undefined);
  await page.reload(); await enterFixtureProject(page, projectFile); await openStoryMode(page, 'script');
  await expect(page.locator('.text-source-panel .line-effect-chip[data-action-kind="visual"]')).toHaveCount(4);
  await page.screenshot({ path: path.join(output, 'reopened.png') });
  checks.push('文本模式只有一个显示文字入口，可选择字体和动画；普通文字保持无动画，保存和重开后四段文字完整保留');
  assert.deepEqual(errors, []);
  await fs.writeFile(path.join(output, 'report.json'), JSON.stringify({ status: 'passed', checks, errors }, null, 2));
} catch (error) {
  await page.screenshot({ path: path.join(output, 'failure.png') }).catch(() => undefined);
  await fs.writeFile(path.join(output, 'report.json'), JSON.stringify({ status: 'failed', phase, error: String(error), checks, errors }, null, 2));
  throw error;
} finally {
  await app.close();
  const cleanup = await cleanVerificationDirectories(output, ['project', 'profile']);
  assert.deepEqual(cleanup.errors, []);
  console.log(output);
}
