import { promises as fs } from 'node:fs';
import path from 'node:path';
import { expect } from '@playwright/test';
import { projectSchema } from '../src/core/model';
import { launchDesktopFixture } from './lib/desktop-fixture';
import { createGalleryFixture } from './lib/gallery-fixture';

const root = path.resolve('.'), output = path.join(root, 'artifacts/gallery-editor', new Date().toISOString().replaceAll(':', '-'));
const fixture = path.join(output, 'project'), projectFile = path.join(fixture, 'project.vns.json');
const project = await createGalleryFixture(fixture), original = await fs.readFile(projectFile, 'utf8');
const app = await launchDesktopFixture({ root, profile: path.join(output, 'profile'), projectFile });
const page = await app.firstWindow(), errors: string[] = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await expect(page.locator('.project-title strong')).toHaveText(project.name, { timeout: 45000 });
  await page.locator('[data-workspace-tab="ui"]').click();
  await page.getByLabel('设计页面', { exact: true }).selectOption({ label: '画廊' });
  const component = page.locator('[data-component-id="test_gallery"]');
  await expect(component.locator('[data-gallery-index]')).toHaveCount(8);
  await expect(component.locator('[data-gallery-page]')).toHaveCount(12);
  await expect.poll(() => component.locator('[data-gallery-thumbnail]').evaluateAll(images => images.every(i => (i as HTMLImageElement).complete && (i as HTMLImageElement).naturalWidth > 0))).toBe(true);
  await expect(component.locator('[data-gallery-thumbnail]').first()).toHaveAttribute('src', /thumb\.png/);
  await page.locator('[data-hierarchy-id="test_gallery"]').click();
  await expect(page.getByLabel('启用图鉴分组', { exact: true })).toBeChecked();
  await page.getByText('画廊图片与分页位置', { exact: true }).click();
  await page.getByText('缩略图状态明暗', { exact: true }).click();
  await page.getByLabel('缩略图普通亮度 %', { exact: true }).fill('75');
  await page.getByLabel('缩略图普通亮度 %', { exact: true }).press('Tab');
  await expect(component.locator('[data-gallery-thumbnail]').first()).toHaveCSS('filter', 'brightness(0.75)');
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  await expect(component.locator('[data-gallery-thumbnail]').first()).toHaveCSS('filter', 'none');
  await expect(page.getByLabel(/^图鉴分组（/).locator('option')).toHaveCount(94);
  await page.getByLabel('搜索图鉴分组', { exact: true }).fill('94');
  await expect(page.getByLabel(/^图鉴分组（/).locator('option')).toHaveCount(1);
  await page.getByLabel('分组名称', { exact: true }).fill('最终组');
  await expect(page.getByLabel('分组名称', { exact: true })).toHaveValue('最终组');
  await page.getByLabel(/^图鉴分组（/).selectOption('group_0');
  await page.getByRole('button', { name: '浏览分组缩略图', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: '预览资源 full_c', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: '使用所选资源', exact: true }).click();
  await expect(component.locator('[data-gallery-thumbnail]').first()).toHaveAttribute('src', /full_c\.png/);
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  await expect(component.locator('[data-gallery-thumbnail]').first()).toHaveAttribute('src', /thumb\.png/);
  await expect(page.locator('[data-gallery-variant]')).toHaveCount(3);
  await page.getByRole('button', { name: '下移分镜 1', exact: true }).click();
  expect(await page.locator('[data-gallery-variant]').evaluateAll(items => items.map(item => item.getAttribute('data-gallery-variant')))).toEqual(['full_a', 'full_c', 'full_b']);
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  expect(await page.locator('[data-gallery-variant]').evaluateAll(items => items.map(item => item.getAttribute('data-gallery-variant')))).toEqual(['full_c', 'full_a', 'full_b']);
  await page.getByRole('button', { name: '重做', exact: true }).click();
  await page.getByRole('button', { name: '移除分镜 3', exact: true }).click();
  await expect(page.locator('[data-gallery-variant]')).toHaveCount(2);
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  await expect(page.locator('[data-gallery-variant]')).toHaveCount(3);
  await page.getByRole('button', { name: '下移分组', exact: true }).click();
  await expect(component.locator('.ui-collection-preview-caption').first()).toHaveText('第 2 组');
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  await expect(component.locator('.ui-collection-preview-caption').first()).toHaveText('第 1 组');
  await page.getByRole('button', { name: '新增分组', exact: true }).click();
  await expect(page.getByLabel(/^图鉴分组（/).locator('option')).toHaveCount(95);
  await page.getByLabel('分组名称', { exact: true }).fill('测试新组');
  await page.getByRole('button', { name: '浏览添加分镜', exact: true }).click();
  const picker = page.getByRole('dialog');
  await picker.getByRole('button', { name: /full_b/ }).click();
  await picker.getByRole('button', { name: '使用所选资源', exact: true }).click();
  await expect(page.locator('[data-gallery-variant]')).toHaveCount(1);
  await page.getByRole('button', { name: '删除分组', exact: true }).click();
  await expect(page.getByLabel(/^图鉴分组（/).locator('option')).toHaveCount(94);
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  await expect(page.getByLabel(/^图鉴分组（/).locator('option')).toHaveCount(95);
  await page.getByLabel('最后一张再点击', { exact: true }).selectOption('loop');
  await page.getByLabel('详情图片缩放', { exact: true }).selectOption('contain');
  await page.getByLabel('详情显示翻页和关闭按钮', { exact: true }).check();
  await page.getByLabel('最多同时显示页码', { exact: true }).fill('9');
  await page.getByLabel('最多同时显示页码', { exact: true }).press('Tab');
  await expect(component.locator('[data-gallery-page]')).toHaveCount(9);
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  await expect(component.locator('[data-gallery-page]')).toHaveCount(12);
  await page.getByText('页码大小与文字', { exact: true }).click();
  for (const [label, value] of [['页码按钮宽度', '84'], ['页码按钮高度', '67'], ['页码按钮间距', '0'], ['页码字号', '40']]) {
    await page.getByLabel(label, { exact: true }).fill(value); await page.getByLabel(label, { exact: true }).press('Tab');
  }
  await page.getByLabel('页码粗体', { exact: true }).check();
  await expect(component.locator('[data-gallery-pagination]')).toHaveCSS('font-weight', '700');
  const componentBox = (await component.boundingBox())!, pageBox = (await component.locator('[data-gallery-page]').first().boundingBox())!;
  expect(Math.abs(pageBox.width / componentBox.width - 84 / (1920 * .94))).toBeLessThan(.001);
  expect(await fs.readFile(projectFile, 'utf8')).toBe(original);
  await page.getByLabel(/^图鉴分组（/).selectOption('group_0');
  await page.getByLabel('分组名称', { exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(output, 'group-editor.png') });
  await page.getByRole('button', { name: '保存界面', exact: true }).click();
  const stored = async () => projectSchema.parse(JSON.parse(await fs.readFile(projectFile, 'utf8'))).ui.components.find(c => c.id === 'test_gallery')!.list!;
  await expect.poll(async () => (await stored()).galleryGroups?.length).toBe(95);
  expect((await stored()).galleryGroups![0].assetIds).toEqual(['full_a', 'full_c', 'full_b']);
  expect((await stored()).galleryGroups![93].name).toBe('最终组');
  expect((await stored()).galleryGroups![94].assetIds).toEqual(['full_b']);
  expect((await stored()).galleryEndAction).toBe('loop');
  expect((await stored()).pageButtonWidth).toBe(84); expect((await stored()).pageFontSize).toBe(40); expect((await stored()).pageBold).toBe(true);
  await page.reload();
  await expect(page.locator('.project-title strong')).toHaveText(project.name, { timeout: 45000 });
  await page.locator('[data-workspace-tab="ui"]').click();
  await page.getByLabel('设计页面', { exact: true }).selectOption({ label: '画廊' });
  await page.locator('[data-hierarchy-id="test_gallery"]').click();
  await expect(page.getByLabel(/^图鉴分组（/).locator('option')).toHaveCount(95);
  await expect(page.getByLabel('最后一张再点击', { exact: true })).toHaveValue('loop');
  await expect(component.locator('[data-gallery-page]')).toHaveCount(12);
  expect(errors).toEqual([]);
  await fs.writeFile(path.join(output, 'report.json'), JSON.stringify({ status: 'passed', compiledBuild: true, checks: ['94组搜索与独立缩略图，12页预览', '新建/删除/重命名/排序分组，增删/排序分镜', '详情缩放、末项行为、控制按钮和页码数量字段', '撤销重做、保存前磁盘不变、显式保存重载'], errors }, null, 2));
  console.log(output);
} catch (error) { await page.screenshot({ path: path.join(output, 'failure.png') }).catch(() => undefined); throw error; }
finally { await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().forEach(w => w.destroy())).catch(() => undefined); await app.close(); }

