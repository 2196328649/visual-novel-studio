import assert from 'node:assert/strict';
import { expect, type ElectronApplication, type Page } from '@playwright/test';
import { createServer } from 'vite';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { createProject } from '../src/core/model';
import { applyTextScript, projectToText } from '../src/core/text-script';
import { isStandaloneNode } from '../src/core/standalone-performance';
import { launchDesktopFixture } from './lib/desktop-fixture';

const root = path.resolve('.'), output = path.join(root, 'artifacts/unified-blueprint', new Date().toISOString().replaceAll(':', '-'));
await fs.mkdir(output, { recursive: true });
const parsed = applyTextScript(createProject('蓝图与独立演出验收'), '# 段落：章节进场\n@章节标题：第一章 · 酒醒城破｜节选改编｜7\n@章节配乐\n# 段落：正文\n旁白：城门开了。');
assert.deepEqual(parsed.issues, []);
const chapter = parsed.project.nodes.find(isStandaloneNode)!;
parsed.project.scriptText = { format: 'vns-text-1', content: projectToText(parsed.project) };
const projectFile = path.join(output, 'project.vns.json');
await fs.writeFile(projectFile, JSON.stringify(parsed.project));
const server = await createServer({ root, server: { host: '127.0.0.1', port: 0, watch: { ignored: ['**/artifacts/**', '**/resources/**', '**/release/**'] } } });
await server.listen();
let app: ElectronApplication | undefined, page: Page | undefined;
const errors: string[] = [], checks: string[] = [];
const launch = async () => {
  app = await launchDesktopFixture({ root, profile: path.join(output, 'profile'), projectFile, devUrl: `http://127.0.0.1:${(server.httpServer!.address() as { port: number }).port}` });
  page = await app.firstWindow(); page.on('pageerror', error => errors.push(error.message));
  await expect(page.locator('.project-title strong')).toHaveText(parsed.project.name);
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1600, 1000));
};
try {
  await launch();
  const tabs = page!.locator('.view-tabs');
  await expect(tabs.getByRole('button', { name: '演出', exact: true })).toHaveCount(0);
  await tabs.getByRole('button', { name: '流程图', exact: true }).click();
  await expect(page!.getByLabel('蓝图类型')).toHaveCount(0);
  await expect(page!.locator('.graph-node')).not.toHaveCount(0);
  await page!.screenshot({ path: path.join(output, '01-flowchart.png') });
  await tabs.getByRole('button', { name: '蓝图', exact: true }).click();
  await expect(page!.getByRole('button', { name: '返回剧本', exact: true })).toHaveCount(0);
  await page!.getByLabel('演出目标', { exact: true }).selectOption('node:' + chapter.id + '/');
  await expect(page!.getByRole('button', { name: '转为可编辑演出', exact: true })).toHaveCount(0);
  await expect(page!.getByLabel('演出用途', { exact: true })).toHaveValue('standalone');
  await expect(page!.locator('.timeline-clip')).toHaveCount(1);
  await expect(page!.locator('.timeline-clip')).toContainText('7.00s');
  await expect(page!.getByLabel('对话界面预览', { exact: true })).toHaveCount(0);
  const stage = await page!.locator('.preview-stage-frame > .text-stage').boundingBox();
  const frame = await page!.locator('.preview-stage-frame').boundingBox();
  assert.ok(stage && frame && stage.width > 200 && stage.height > 100);
  assert.ok(stage.y >= frame.y - 1 && stage.y + stage.height <= frame.y + frame.height + 1);
  assert.ok(Math.abs(stage.width / stage.height - parsed.project.width / parsed.project.height) < .01);
  await page!.screenshot({ path: path.join(output, '02-chapter-standalone.png') });
  checks.push('章节转独立演出保留七秒时间轴，独立预览无对白框');
  for (const [width, height] of [[1024, 680], [1280, 720], [1920, 1080]]) {
    await app!.evaluate(({ BrowserWindow }, size) => BrowserWindow.getAllWindows()[0].setContentSize(size[0], size[1]), [width, height]);
    await page!.getByRole('button', { name: '添加片段', exact: true }).click();
    await page!.locator('.timeline-clip').first().click();
    await page!.locator('.timeline-inspector .timeline-parameter button').last().scrollIntoViewIfNeeded();
    await expect.poll(() => page!.locator('.performance-timeline').evaluate(el => el.scrollHeight - el.clientHeight)).toBeLessThanOrEqual(2);
    await expect(page!.getByLabel('演出预览进度', { exact: true })).toBeVisible();
    const bounds = await page!.locator('.timeline-scroll').boundingBox();
    assert.ok(bounds && bounds.height >= 130 && bounds.y + bounds.height <= (await page!.evaluate(() => innerHeight)) - 20);
    await page!.screenshot({ path: path.join(output, `timeline-${width}.png`) });
    await page!.getByRole('button', { name: '添加片段', exact: true }).click();
  }
  checks.push('1024×680、1280×720、1920×1080 展开菜单和参数后时间轴没有纵向溢出，底部参数可滚动到达');
  const duration = page!.locator('.timeline-parameter').filter({ has: page!.getByText('时长', { exact: true }) }).locator('input');
  await duration.fill('600'); await duration.press('Tab');
  await page!.getByRole('button', { name: '适合窗口', exact: true }).click();
  await expect.poll(() => page!.locator('.timeline-scroll').evaluate(el => el.scrollWidth - el.clientWidth)).toBeLessThanOrEqual(2);
  await expect(page!.locator('.timeline-ruler')).toContainText('600');
  await page!.screenshot({ path: path.join(output, 'timeline-long.png') });
  await duration.fill('7'); await duration.press('Tab');
  checks.push('十分钟演出可完整适配窗口，刻度覆盖末尾，缩放不再受 24% 下限限制');
  await page!.getByRole('button', { name: '节点蓝图', exact: true }).click();
  await expect(page!.locator('.generic-blueprint-workspace')).toBeVisible();
  await page!.getByRole('button', { name: '时间轴', exact: true }).click();
  await page!.getByLabel('新建演出类型', { exact: true }).selectOption('dialogue');
  await page!.getByRole('button', { name: '新建演出', exact: true }).click();
  await expect(page!.getByLabel('演出用途', { exact: true })).toHaveValue('dialogue');
  await expect(page!.getByLabel('对话界面预览', { exact: true })).toBeVisible();
  await page!.screenshot({ path: path.join(output, '03-dialogue.png') });
  checks.push('台词演出有对白预览，两种演出可切换时间轴和节点编辑');
  await page!.getByLabel('新建演出类型', { exact: true }).selectOption('standalone');
  await page!.getByRole('button', { name: '新建演出', exact: true }).click();
  await expect(page!.getByLabel('演出用途', { exact: true })).toHaveValue('standalone');
  await page!.getByRole('button', { name: '新建逻辑蓝图', exact: true }).click();
  await expect(page!.locator('.performance-workspace-body')).toHaveClass(/logic-only/);
  await expect(page!.locator('.generic-blueprint-workspace')).toBeVisible();
  await page!.screenshot({ path: path.join(output, '04-logic.png') });
  await page!.getByRole('button', { name: '保存工程', exact: true }).click();
  await expect(page!.locator('.dirty-dot')).toHaveCount(0);
  const saved = JSON.parse(await fs.readFile(projectFile, 'utf8'));
  assert.equal(saved.blueprints.length, 4);
  assert.equal(saved.nodes.find((node: { id: string }) => node.id === chapter.id).lines[0].silent, true);
  assert.equal(saved.blueprints.filter((graph: { performanceKind?: string }) => graph.performanceKind === 'standalone').length, 2);
  await app!.close(); app = undefined;
  await launch();
  await page!.locator('.view-tabs').getByRole('button', { name: '蓝图', exact: true }).click();
  await expect(page!.getByLabel('演出目标', { exact: true }).locator('option[value^="graph:"]')).toHaveCount(4);
  checks.push('通用逻辑编辑、两类新建、保存与重开通过');
  assert.deepEqual(errors, []);
  await fs.writeFile(path.join(output, 'report.json'), JSON.stringify({ status: 'passed', checks, errors }, null, 2));
  console.log(output);
} catch (error) {
  await page?.screenshot({ path: path.join(output, 'failure.png') }).catch(() => undefined);
  await fs.writeFile(path.join(output, 'failure.json'), JSON.stringify({ error: String(error), checks, errors }, null, 2));
  throw error;
} finally { await app?.close(); await server.close(); }
