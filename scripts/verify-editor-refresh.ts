import assert from 'node:assert/strict';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { expect } from '@playwright/test';
import { PNG } from 'pngjs';
import { createProject, projectSchema } from '../src/core/model';
import { createChapterPerformance } from '../src/core/chapter-performances';
import { projectToText } from '../src/core/text-script';
import { launchDesktopFixture } from './lib/desktop-fixture';
import { openStoryMode } from './lib/story-workspace';

const root = path.resolve('.'), output = path.join(root, 'artifacts/editor-refresh', new Date().toISOString().replaceAll(':', '-'));
await fs.mkdir(output, { recursive: true });
const projectDir = path.join(output, 'project'); await fs.mkdir(projectDir);
const project = createProject('编辑器整理验收');
const png = new PNG({ width: 160, height: 90 });
for (let i = 0; i < png.data.length; i += 4) { png.data[i] = 65; png.data[i + 1] = 105; png.data[i + 2] = 135; png.data[i + 3] = 255; }
await fs.writeFile(path.join(projectDir, 'image.png'), PNG.sync.write(png));
project.assets.push({ id: 'image', name: '章节题图', kind: 'image', path: 'image.png' });
project.characters = Array.from({ length: 28 }, (_, index) => ({ id: 'character_' + index, name: '角色 ' + index, color: '#88bbcc', expressions: Array.from({ length: 8 }, (_, e) => ({ id: `expression_${index}_${e}`, name: '表情 ' + e, assetId: 'image' })) }));
const textGraph = createChapterPerformance(project, 'text', { kind: 'chapter', title: '第一章', subtitle: '归途', backgroundId: 'image', duration: 12, effect: 'ink' });
const imageGraph = createChapterPerformance(project, 'image', { kind: 'chapter', title: '不会重复显示', subtitle: '图片模式', titleImageId: 'image', backgroundId: 'image', duration: 7, effect: 'ink' });
// Exercise editable timeline components directly; built-in chapter entrypoints now wrap these in callable graphs.
delete textGraph.chapterVariant; delete imageGraph.chapterVariant;
project.blueprints.push(textGraph, imageGraph);
const passage = project.nodes.find(node => node.kind === 'passage')!;
passage.name = '章节演出调用'; passage.lines = [{ id: 'chapter_line', text: '', silent: true, actions: [{ kind: 'blueprint', blueprintId: textGraph.id }] }];
project.scriptText = { format: 'vns-text-1', standaloneSyntax: 'module-names', content: projectToText(project) };
const projectFile = path.join(projectDir, 'project.vns.json'); await fs.writeFile(projectFile, JSON.stringify(project));
const launch = () => launchDesktopFixture({ root, projectFile, profile: path.join(output, 'profile') });
let app = await launch(), page = await app.firstWindow(), phase = 'launch';
const checks: string[] = [], errors: string[] = [], metrics: Record<string, unknown> = {};
page.on('pageerror', error => errors.push(error.message));
const capture = (name: string) => page.screenshot({ path: path.join(output, name + '.png') });
const close = async () => { await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().forEach(window => window.destroy())); await app.close(); };
const save = async () => { const button = page.getByRole('button', { name: '保存工程', exact: true }); if (await button.isEnabled()) await button.click(); await expect(page.locator('.dirty-dot')).toHaveCount(0); return projectSchema.parse(JSON.parse(await fs.readFile(projectFile, 'utf8'))); };
try {
  await expect(page.locator('.project-title strong')).toHaveText(project.name, { timeout: 45000 });
  await app.evaluate(({ BrowserWindow }) => { const window = BrowserWindow.getAllWindows()[0]; window.unmaximize(); window.setContentSize(1440, 900); });
  phase = 'character layout';
  await page.locator('[data-workspace-tab="characters"]').click();
  await page.locator('[data-character-id="character_0"]').click();
  await expect(page.getByRole('region', { name: '角色编辑工作区' })).toBeVisible();
  await page.getByLabel('角色名称', { exact: true }).fill('主角 · 已整理');
  await expect(page.locator('[data-character-id="character_0"]')).toContainText('主角 · 已整理');
  await page.getByRole('tab', { name: '构图与站位', exact: true }).click();
  await expect(page.getByRole('tab', { name: '继承与功能', exact: true })).toHaveCount(0);
  await page.getByRole('tab', { name: '外观与表情', exact: true }).click();
  metrics.characterWidth = await page.locator('.character-workspace').evaluate(e => e.clientWidth);
  assert.ok(Number(metrics.characterWidth) >= 600);
  await capture('01-characters');
  await page.getByRole('button', { name: '新建文件夹', exact: true }).click();
  await page.getByLabel('角色文件夹名称', { exact: true }).fill('主角组');
  await page.locator('.character-folder-form').getByRole('button', { name: '创建', exact: true }).click();
  await page.getByLabel('角色所在文件夹', { exact: true }).selectOption({ label: '主角组' });
  await expect(page.locator('[data-character-id="character_0"]')).toBeVisible();
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  await expect(page.locator('[data-character-id="character_0"]')).toHaveCount(0);
  await page.getByRole('button', { name: '重做', exact: true }).click();
  await expect(page.locator('[data-character-id="character_0"]')).toBeVisible();
  checks.push('角色目录、列表和宽幅编辑区；两个常用页签、重命名、分组、撤销重做。');

  phase = 'timeline viewport';
  await page.locator('[data-workspace-tab="blueprint"]').click();
  await page.getByLabel('演出目标', { exact: true }).selectOption('graph:' + textGraph.id);
  const canvas = page.getByLabel('时间轴画布', { exact: true });
  await expect(canvas).toBeVisible();
  await page.locator('.timeline-clip').first().click();
  const beforeFit = await canvas.getAttribute('data-zoom');
  await page.getByLabel('片段显示时长', { exact: true }).fill('20');
  await page.getByLabel('片段显示时长', { exact: true }).press('Tab');
  await expect(canvas).toHaveAttribute('data-zoom', beforeFit!);
  await page.getByLabel('轨道缩放', { exact: true }).selectOption('100');
  await canvas.evaluate(e => { e.scrollLeft = 400; e.dispatchEvent(new Event('scroll')); });
  const ruler = await page.getByLabel('时间标尺', { exact: true }).boundingBox(), canvasBox = await canvas.boundingBox(); assert.ok(ruler && canvasBox);
  await page.mouse.click(canvasBox.x + 330, ruler.y + 10);
  await expect(page.getByLabel('当前时间', { exact: true })).not.toHaveText('0.00 秒');
  const time = await page.getByLabel('当前时间', { exact: true }).textContent();
  const left = await canvas.evaluate(e => e.scrollLeft);
  await page.getByLabel('片段显示时长', { exact: true }).fill('8');
  await page.getByLabel('片段显示时长', { exact: true }).press('Tab');
  await expect(canvas).toHaveAttribute('data-zoom', '100');
  assert.equal(await canvas.evaluate(e => e.scrollLeft), left);
  await expect(page.getByLabel('当前时间', { exact: true })).toHaveText(time!);
  await page.getByRole('tab', { name: '时间轴组件', exact: true }).click();
  await page.locator('.timeline-public-inputs').getByLabel('标题', { exact: true }).fill('第一章 · 新标题');
  assert.equal(await canvas.evaluate(e => e.scrollLeft), left);
  await expect(page.getByLabel('当前时间', { exact: true })).toHaveText(time!);
  metrics.timeline = { left, time, initialZoom: beforeFit };
  await capture('02-timeline');
  checks.push('修改片段时长不触发自动缩放；缩短片段、编辑参数和切换属性保留横向滚动与播放头。');

  phase = 'chapter variants and objects';
  await page.getByLabel('演出目标', { exact: true }).selectOption('graph:' + imageGraph.id);
  await page.getByRole('tab', { name: '时间轴组件', exact: true }).click();
  await expect(page.locator('.timeline-public-inputs').getByLabel('章节题图', { exact: true })).toBeVisible();
  await expect(page.getByLabel('标题', { exact: true })).toHaveCount(0);
  await expect(page.getByLabel('副标题', { exact: true })).toHaveCount(0);
  const particles = page.getByLabel('实例生命周期 标题字形粒子', { exact: true }).locator('.lifetime-span');
  await particles.click();
  await expect(page.getByLabel('片段颜色', { exact: true })).toHaveValue('#ffffff');
  await page.getByLabel('片段颜色', { exact: true }).fill('#f0a040');
  await expect(page.getByLabel('片段颜色', { exact: true })).toHaveValue('#f0a040');
  await capture('03-image-chapter');
  checks.push('文字版和图片版参数分开；背景、标题、粒子与淡入淡出子对象可在时间轴中选择。');

  phase = 'inline overrides';
  await openStoryMode(page, 'script');
  const call = page.locator('.blueprint-call-inputs').first();
  await expect(call).toBeVisible();
  await expect(call).not.toContainText('本次单独设置');
  const row = call.locator('.blueprint-call-parameter').filter({ has: page.getByRole('checkbox', { name: '单独设置标题', exact: true }) });
  const check = row.getByRole('checkbox'); await check.check();
  const input = row.getByRole('textbox'); await input.fill('本次章节标题');
  const boxes = await row.evaluate(e => { const label = e.querySelector('label')!.getBoundingClientRect(), field = e.querySelector('fieldset')!.getBoundingClientRect(); return { label: label.toJSON(), field: field.toJSON() }; });
  assert.ok(Math.abs(boxes.label.y - boxes.field.y) < Math.max(boxes.label.height, boxes.field.height));
  let saved = await save();
  const savedPassage = saved.nodes.find(n => n.id === passage.id); assert.ok(savedPassage?.kind === 'passage');
  assert.equal(savedPassage.lines[0].actions[0].kind === 'blueprint' && savedPassage.lines[0].actions[0].inputs?.title, '本次章节标题');
  await check.uncheck(); await expect(input).toBeDisabled();
  await expect(input).toHaveValue('第一章 · 新标题');
  await capture('04-inline-parameters');
  checks.push('覆盖复选框与值同一行，启用后写入本次调用，取消后恢复蓝图默认值。');

  phase = 'small window and reopen';
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1100, 760));
  for (const workspace of ['characters', 'blueprint']) {
    await page.locator(`[data-workspace-tab="${workspace}"]`).click();
    const size = await page.evaluate(() => ({ width: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth }));
    assert.ok(size.scroll <= size.width + 1, JSON.stringify(size));
    await capture('05-small-' + workspace);
  }
  saved = await save();
  await close(); app = await launch(); page = await app.firstWindow();
  await expect(page.locator('.project-title strong')).toHaveText(project.name, { timeout: 45000 });
  await page.locator('[data-workspace-tab="characters"]').click();
  await page.getByRole('button', { name: /^全部角色/ }).click();
  await expect(page.locator('[data-character-id="character_0"]')).toContainText('主角 · 已整理');
  assert.equal(saved.blueprints.find(g => g.id === textGraph.id)!.exposedInputs.find(p => p.id === 'title')!.defaultValue, '第一章 · 新标题');
  checks.push('1100×760 两个工作区无页面横向溢出；保存重开保留角色、文件夹和演出参数。');
  assert.deepEqual(errors, []);
  await fs.writeFile(path.join(output, 'report.json'), JSON.stringify({ status: 'passed', checks, metrics, errors }, null, 2));
  console.log(output);
} catch (error) {
  await capture('failure').catch(() => undefined);
  await fs.writeFile(path.join(output, 'failure.html'), await page.content());
  await fs.writeFile(path.join(output, 'report.json'), JSON.stringify({ status: 'failed', phase, checks, metrics, errors, error: String(error) }, null, 2));
  console.log(output); throw error;
} finally { await close().catch(() => undefined); }
