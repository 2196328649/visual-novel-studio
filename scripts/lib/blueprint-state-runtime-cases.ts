import type { createBlueprintStateFixture } from './blueprint-state-fixture';

export function blueprintStateRuntimeCases(f: ReturnType<typeof createBlueprintStateFixture>, start: string[], open: string[], close: string[]) {
  const q = JSON.stringify, state = (page: string) => 'vn_ui_state_get(' + q(page) + ', ' + q(f.counterId) + ')';
  const click = (id: string) => '    click id ' + q('vn_component_' + id) + ' pos (0.5, 0.5)';
  return [
    'init python:',
    '    def vn_test_author_state_contract_rejected(callback):',
    '        try:',
    '            callback()',
    '        except Exception as error:',
    '            return "目标页面的状态类型" in str(error)',
    '        return False', '',
    'testcase author_dynamic_page_contract:', ...start, ...open,
    '    assert eval (vn_ui_state_get(' + q(f.root.id) + ', ' + q(f.counterId) + ', "number") == 0)',
    '    assert eval (vn_test_author_state_contract_rejected(lambda: vn_ui_state_get(' + q(f.root.id) + ', ' + q(f.counterId) + ', "boolean")))',
    '    assert eval (vn_test_author_state_contract_rejected(lambda: vn_ui_state_set(' + q(f.root.id) + ', ' + q(f.counterId) + ', 7, "boolean")))',
    '    assert eval (' + state(f.root.id) + ' == 0)',
    '    $ vn_ui_state_set(' + q(f.root.id) + ', ' + q(f.counterId) + ', 7, "number")',
    '    assert eval (' + state(f.root.id) + ' == 7)',
    ...close, '',
    'testcase author_page_instances:', ...start, ...open,
    '    assert eval (' + state(f.root.id) + ' == 0)',
    click('state_root_increment'), click('state_root_increment'),
    '    assert eval (' + state(f.root.id) + ' == 2 and vn_var_state_event_local == 1 and vn_var_state_shared_read == 2)',
    click('state_open_child'), '    pause until eval (' + q(f.childA.id) + ' in vn_ui_open_pages)',
    click('state_child_increment'),
    '    assert eval (' + state(f.childA.id) + ' == 11 and ' + state(f.root.id) + ' == 2)',
    click(f.childA.components[1].id), '    pause until eval (' + q(f.childA.id) + ' not in vn_ui_open_pages)',
    click('state_open_child'), '    pause until eval (' + q(f.childA.id) + ' in vn_ui_open_pages)',
    '    assert eval (' + state(f.childA.id) + ' == 10 and ' + state(f.root.id) + ' == 2)',
    click(f.childA.components[1].id), '    pause until eval (' + q(f.childA.id) + ' not in vn_ui_open_pages)',
    ...close, '    assert eval (not vn_ui_state_records)', '',

    'testcase author_native_template_instances:', ...start, ...open,
    click('state_root_increment'), click('state_open_native'),
    '    pause until screen "preferences"',
    '    assert eval (vn_ui_native_page_is_open("ui:preferences"))',
    '    assert eval (' + q(f.root.id) + ' not in vn_ui_visible_page_order() and not vn_ui_page_interactive(' + q(f.root.id) + '))',
    '    assert eval (' + state('ui:preferences') + ' == 100 and ' + state(f.root.id) + ' == 1)',
    click('state_native_increment'),
    '    assert eval (' + state('ui:preferences') + ' == 101 and vn_var_state_event_local == 1 and vn_var_state_shared_read == 101)',
    click('state_native_child'), '    pause until eval (' + q(f.childA.id) + ' in vn_ui_open_pages)',
    '    assert eval (' + q(f.childA.id) + ' in vn_ui_visible_page_order() and ' + q(f.root.id) + ' not in vn_ui_visible_page_order())',
    click('state_child_increment'),
    '    assert eval (' + state(f.childA.id) + ' == 11 and ' + state('ui:preferences') + ' == 101)',
    click(f.childA.components[1].id), '    pause until eval (' + q(f.childA.id) + ' not in vn_ui_open_pages)',
    click('state_native_close'), '    pause until eval (vn_var_state_native_done == 1)',
    '    assert eval (vn_var_state_native_result == "native-ok" and ' + state(f.root.id) + ' == 1)',
    '    assert eval (vn_ui_page_interactive(' + q(f.root.id) + ') and not vn_ui_native_page_is_open("ui:preferences"))',
    '    screenshot "unified-native-page-return.png"',
    click('state_open_native'), '    pause until screen "preferences"',
    '    assert eval (' + state('ui:preferences') + ' == 100)',
    click('state_native_close'), '    pause until eval (vn_ui_page_interactive(' + q(f.root.id) + '))',
    ...close, '    assert eval (not vn_ui_state_records)', '',

    ...([0, .2] as const).flatMap(elapsed => [
      'testcase author_state_save_' + (elapsed ? 'partial' : 'immediate') + ':', ...start,
      '    run Jump(' + q('vn_node_' + f.saved.id) + ')',
      '    pause until eval (vn_var_ready == 1)',
      '    pause ' + elapsed,
      '    assert eval (vn_bp_frame.get("locals", {}).get("captured") == 11)',
      click('state_root_increment'),
      '    assert eval (' + state(f.root.id) + ' == 1)',
      '    $ renpy.test.testexecution.author_saved_frame = vn_bp_frame',
      '    run FileSave("author_state_wait", confirm=False, slot=True)',
      click('state_root_increment'),
      '    assert eval (' + state(f.root.id) + ' == 2)',
      '    run FileLoad("author_state_wait", confirm=False, slot=True)',
      '    pause until eval (' + q(f.root.id) + ' in vn_ui_open_pages)',
      '    assert eval (' + state(f.root.id) + ' == 1 and vn_var_ready == 1 and vn_var_done_a == 0)',
      '    assert eval (vn_bp_frame == renpy.test.testexecution.author_saved_frame)',
      click('invoke_cache_b'), '    pause until eval (vn_var_done_b == 1)',
      '    assert eval (vn_var_cache_b == 22 and vn_bp_frame.get("locals", {}).get("captured") == 11)',
      '    pause until eval (vn_var_done_a == 1)',
      '    assert eval (vn_var_cache_a == 11 and ' + state(f.root.id) + ' == 1)',
      click(f.root.components[1].id), '    pause until "可保存调用已完成。"',
      '    assert eval (not vn_ui_state_records and vn_bp_frame is None)',
      '    run Rollback()', '    pause until "准备检查调用隔离。"',
      '    assert eval (not vn_ui_open_pages and not vn_ui_state_records and vn_var_ready == 0)', '',
    ]),

    'testcase author_state_legacy_shapes:', ...start, ...open,
    click('state_root_increment'), '    assert eval (' + state(f.root.id) + ' == 1)',
    '    $ vn_ui_state_records = {}',
    '    assert eval (' + state(f.root.id) + ' == 0)',
    '    $ renpy.test.testexecution.author_outer_frame = vn_bp_frame',
    '    $ vn_bp_frame = dict(graph=' + q(f.cache.id) + ', values={})',
    '    assert eval (vn_bp_state_get(' + q(f.cache.id) + ', "captured") == -99)',
    '    $ renpy.test.testexecution.author_old_frame = vn_bp_frame',
    '    $ vn_bp_state_set(' + q(f.cache.id) + ', "captured", 7)',
    '    assert eval ("locals" not in renpy.test.testexecution.author_old_frame)',
    '    assert eval (vn_bp_state_get(' + q(f.cache.id) + ', "captured") == 7)',
    '    $ vn_bp_frame = dict(vn_bp_frame, locals={"captured": "old-type"})',
    '    assert eval (vn_bp_state_get(' + q(f.cache.id) + ', "captured") == -99)',
    '    assert eval (not vn_state_valid({"type": "number"}, True) and not vn_state_valid({"type": "boolean"}, 1))',
    '    $ vn_bp_frame = renpy.test.testexecution.author_outer_frame',
    ...close, '',
  ];
}
